    UNION ALL SELECT * FROM "GA4"."GA4_OBFUSCATED_SAMPLE_ECOMMERCE"."EVENTS_20201231"
),
page_paths AS (                -- 2. isolate cleaned paths for genuine “page_view” events
    SELECT REGEXP_REPLACE(
             REGEXP_SUBSTR(
               f.value:"value":"string_value"::STRING,
               'https://shop\\.googlemerchandisestore\\.com/(.*)', 1, 1, 'e', 1),
             '/{2,}', '/'
           )         AS "clean_path"
    FROM dec_events      e,
         LATERAL FLATTEN(input => e."EVENT_PARAMS") f
    WHERE e."EVENT_NAME"                   = 'page_view'
      AND f.value:"key"::STRING            = 'page_location'
      AND f.value:"value":"string_value" ILIKE 'https://shop.googlemerchandisestore.com/%'
),
hit_counts AS (               -- 3. count page views per cleaned path
    SELECT "clean_path",
           COUNT(*) AS "page_views"
    FROM page_paths
    GROUP BY "clean_path"
)
-- 4. rank by page-view count and return the 2nd-highest path
SELECT "clean_path"
FROM (
    SELECT "clean_path",
           "page_views",
           RANK() OVER (ORDER BY "page_views" DESC) AS "rk"
    FROM hit_counts
) r
WHERE r."rk" = 2;