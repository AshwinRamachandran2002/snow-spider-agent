    SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201231"
),
page_counts AS (
    SELECT
        REGEXP_REPLACE(
            REGEXP_REPLACE(
                ep.value:"value":"string_value"::STRING,
                '^https?://shop\.googlemerchandisestore\.com', ''
            ),
            '/{2,}', '/'
        )                                             AS clean_page_path,
        COUNT(*)                                      AS page_views
    FROM december_events AS t,
         LATERAL FLATTEN(input => t."EVENT_PARAMS") ep
    WHERE t."EVENT_NAME" = 'page_view'
      AND ep.value:"key"::STRING = 'page_location'
      AND ep.value:"value":"string_value"::STRING ILIKE '%shop.googlemerchandisestore.com%'
    GROUP BY clean_page_path
)
SELECT clean_page_path,
       page_views
FROM (
    SELECT *,
           ROW_NUMBER() OVER (ORDER BY page_views DESC) AS rn
    FROM page_counts
)
WHERE rn = 2
ORDER BY page_views DESC
LIMIT 1;