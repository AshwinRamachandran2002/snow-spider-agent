),
page_counts AS (
    SELECT
        REGEXP_REPLACE(
            PARSE_URL(f.value:"value":"string_value"::STRING):path::STRING,
            '/{2,}',
            '/'
        )                                           AS "clean_path",
        COUNT(*)                                    AS "page_views"
    FROM  dec2020 t,
          LATERAL FLATTEN(INPUT => t."EVENT_PARAMS") f
    WHERE t."EVENT_NAME"              = 'page_view'
      AND f.value:"key"::STRING       = 'page_location'
      AND f.value:"value":"string_value" IS NOT NULL
      AND f.value:"value":"string_value" <> ''
      AND PARSE_URL(f.value:"value":"string_value"::STRING):host::STRING = 'shop.googlemerchandisestore.com'
    GROUP BY 1
)
SELECT "clean_path",
       "page_views"
FROM (
    SELECT *,
           DENSE_RANK() OVER (ORDER BY "page_views" DESC) AS rnk
    FROM page_counts
)
WHERE rnk = 2;