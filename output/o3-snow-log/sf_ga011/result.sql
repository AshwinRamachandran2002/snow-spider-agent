    UNION ALL SELECT "EVENT_NAME","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201230"
    UNION ALL SELECT "EVENT_NAME","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201231"
),
page_locations AS (             -- 2. Extract & clean page_location values
    SELECT REGEXP_REPLACE(
             SPLIT_PART(f.value:"value":"string_value"::STRING,
                        'shop.googlemerchandisestore.com', 2),
             '/{2,}', '/'
           )                                   AS "clean_path"
    FROM dec_events e,
         LATERAL FLATTEN (INPUT => e."EVENT_PARAMS") f
    WHERE e."EVENT_NAME" = 'page_view'
      AND f.value:"key"::STRING = 'page_location'
      AND f.value:"value":"string_value"::STRING ILIKE '%shop.googlemerchandisestore.com%'
),
page_counts AS (                -- 3. Count views per clean path
    SELECT "clean_path",
           COUNT(*) AS "views"
    FROM page_locations
    GROUP BY "clean_path"
)
-- 4. Return the page with the 2-nd highest view count
SELECT "clean_path", "views"
FROM page_counts
QUALIFY RANK() OVER (ORDER BY "views" DESC NULLS LAST) = 2;