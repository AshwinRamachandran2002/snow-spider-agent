    SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201231"
),                                                         
page_locations AS (       -- 2. Pull page_location for page_view events
    SELECT  
        f.VALUE:"value":"string_value"::STRING AS loc
    FROM dec_events        t,
         LATERAL FLATTEN(input => t."EVENT_PARAMS") f
    WHERE t."EVENT_NAME" = 'page_view'
      AND f.VALUE:"key"::STRING = 'page_location'
      AND f.VALUE:"value":"string_value"::STRING ILIKE '%shop.googlemerchandisestore.com%'
),                                                         
cleaned AS (             -- 3. Strip protocol / domain & collapse duplicate slashes
    SELECT 
        REGEXP_REPLACE(
            '/' || ARRAY_TO_STRING(
                     ARRAY_SLICE( SPLIT(SPLIT_PART(loc,'://',2),'/'), 1, 999 ),
                     '/'
                 ),
            '/{2,}',
            '/'
        ) AS clean_path
    FROM page_locations
),                                                         
ranked AS (              -- 4. Count views & rank
    SELECT
        clean_path,
        COUNT(*)                                        AS page_views,
        ROW_NUMBER() OVER (ORDER BY COUNT(*) DESC)      AS rnk
    FROM cleaned
    GROUP BY clean_path
)
SELECT clean_path, page_views
FROM   ranked
WHERE  rnk = 2;