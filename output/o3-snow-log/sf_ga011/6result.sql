page_views AS (                      -- 2.  Extract clean path & tally page-views
    SELECT
        REGEXP_REPLACE(                          -- remove duplicate slashes
            PARSE_URL(f.value:"value":"string_value"::STRING):path::STRING,
            '/{2,}', 
            '/'
        )                        AS "clean_path",
        COUNT(*)                 AS "page_views"
    FROM dec_events t,
         LATERAL FLATTEN (INPUT => t."EVENT_PARAMS") f
    WHERE t."EVENT_NAME" = 'page_view'
      AND f.value:"key"::STRING = 'page_location'
      AND PARSE_URL(f.value:"value":"string_value"::STRING):host::STRING
          = 'shop.googlemerchandisestore.com'
    GROUP BY "clean_path"
)
SELECT "clean_path"
FROM page_views
ORDER BY "page_views" DESC NULLS LAST   -- highest first
OFFSET 1 ROW                            -- skip the #1 page
FETCH NEXT 1 ROWS ONLY;                 -- return the #2 page