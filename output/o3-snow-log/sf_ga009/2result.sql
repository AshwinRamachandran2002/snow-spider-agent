/* 2. retrieve ga_session_id & session_engaged for each event row */
"EXTRACTED" AS (
    SELECT
        ue."USER_PSEUDO_ID"                                               AS "USER_ID",
        MAX(CASE WHEN f.value:"key"::STRING = 'ga_session_id'
                 THEN f.value:"value":"int_value"::NUMBER END)            AS "GA_SESSION_ID",
        MAX(CASE WHEN f.value:"key"::STRING = 'session_engaged'
                 THEN COALESCE(f.value:"value":"int_value"::NUMBER,
                                f.value:"value":"string_value"::NUMBER)
            END)                                                          AS "SESSION_ENGAGED_FLAG"
    FROM   "UNION_EVENTS" ue
           ,LATERAL FLATTEN(input => ue."EVENT_PARAMS") f
    GROUP  BY ue."USER_PSEUDO_ID",
             ue."EVENT_TIMESTAMP",
             ue."EVENT_NAME"
),

/* 3. keep engaged sessions, de-duplicate on (user, session) */
"ENGAGED_SESSIONS" AS (
    SELECT DISTINCT
           "USER_ID",
           "GA_SESSION_ID"
    FROM   "EXTRACTED"
    WHERE  "SESSION_ENGAGED_FLAG" = 1
      AND  "GA_SESSION_ID"      IS NOT NULL
),

/* 4. sessions per user */
"SESSIONS_PER_USER" AS (
    SELECT "USER_ID",
           COUNT(DISTINCT "GA_SESSION_ID") AS "ENGAGED_SESSION_COUNT"
    FROM   "ENGAGED_SESSIONS"
    GROUP  BY "USER_ID"
)

/* 5. final average */
SELECT AVG("ENGAGED_SESSION_COUNT")::FLOAT AS "AVG_ENGAGED_SESSIONS_PER_USER"
FROM   "SESSIONS_PER_USER";