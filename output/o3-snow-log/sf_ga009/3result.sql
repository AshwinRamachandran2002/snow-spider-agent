    SELECT * FROM "GA4"."GA4_OBFUSCATED_SAMPLE_ECOMMERCE"."EVENTS_20201231"
),

PARAMS AS (                     /* pull ga_session_id and session_engaged flag */
    SELECT
        AE."USER_PSEUDO_ID",
        MAX( CASE WHEN EP.value:key = 'ga_session_id'
                  THEN EP.value:int_value::NUMBER
             END )                           AS "GA_SESSION_ID",
        MAX( CASE WHEN EP.value:key = 'session_engaged'
                  THEN COALESCE( EP.value:string_value,
                                 EP.value:int_value::STRING )
             END )                           AS "SESSION_ENGAGED"
    FROM ALL_EVENTS   AE,
         LATERAL FLATTEN( INPUT => AE."EVENT_PARAMS" ) EP
    GROUP BY AE."USER_PSEUDO_ID", AE."EVENT_TIMESTAMP"   -- one row per event
),

ENGAGED_SESSIONS AS (            /* keep only engaged sessions */
    SELECT DISTINCT
           "USER_PSEUDO_ID",
           "GA_SESSION_ID"
    FROM PARAMS
    WHERE "GA_SESSION_ID"   IS NOT NULL
      AND "SESSION_ENGAGED" = '1'
),

SESSIONS_PER_USER AS (           /* number of engaged sessions per user */
    SELECT
        "USER_PSEUDO_ID",
        COUNT(*) AS "ENGAGED_SESSIONS"
    FROM ENGAGED_SESSIONS
    GROUP BY "USER_PSEUDO_ID"
)

SELECT
    AVG("ENGAGED_SESSIONS") AS "AVG_ENGAGED_SESSIONS_PER_USER"
FROM SESSIONS_PER_USER;