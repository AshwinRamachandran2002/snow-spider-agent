UNION ALL SELECT * FROM "GA4"."GA4_OBFUSCATED_SAMPLE_ECOMMERCE"."EVENTS_20201229"
UNION ALL SELECT * FROM "GA4"."GA4_OBFUSCATED_SAMPLE_ECOMMERCE"."EVENTS_20201230"
UNION ALL SELECT * FROM "GA4"."GA4_OBFUSCATED_SAMPLE_ECOMMERCE"."EVENTS_20201231"
),
/* 2. extract ga_session_id and session_engaged from EVENT_PARAMS */
event_level AS (
    SELECT
           e."USER_PSEUDO_ID"                                                 AS user_pseudo_id,
           MAX( CASE 
                    WHEN f.value:"key"::string = 'ga_session_id' 
                    THEN COALESCE( (f.value:"value":"int_value")::number,
                                   (f.value:"value":"string_value")::number )
                END )                                                        AS ga_session_id,
           MAX( CASE 
                    WHEN f.value:"key"::string = 'session_engaged'
                    THEN COALESCE( (f.value:"value":"int_value")::number,
                                   (f.value:"value":"string_value")::number )
                END )                                                        AS session_engaged_flag
    FROM   events e
           ,LATERAL FLATTEN( INPUT => e."EVENT_PARAMS" ) f
    GROUP  BY e."USER_PSEUDO_ID", e."EVENT_TIMESTAMP"
),
/* 3. one row per engaged session (flag = 1) */
engaged_sessions AS (
    SELECT DISTINCT
           user_pseudo_id,
           ga_session_id
    FROM   event_level
    WHERE  session_engaged_flag = 1
           AND ga_session_id IS NOT NULL
)
/* 4. average engaged-sessions per user */
SELECT
       AVG(session_count) AS "AVG_ENGAGED_SESSIONS_PER_USER"
FROM (
      SELECT user_pseudo_id,
             COUNT(*) AS session_count
      FROM   engaged_sessions
      GROUP  BY user_pseudo_id
);