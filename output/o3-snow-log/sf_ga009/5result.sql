    SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201229" UNION ALL
    SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201230" UNION ALL
    SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201231"
),
/* explode all event_params once per event */
event_params AS (
    SELECT
        e."USER_PSEUDO_ID"                                                    AS user_id,
        e."EVENT_TIMESTAMP"                                                   AS event_ts,
        f.value:"key"::STRING                                                 AS key_name,
        f.value:"value":"int_value"::NUMBER                                   AS int_val,
        f.value:"value":"string_value"::STRING                                AS str_val
    FROM   union_dec_2020 e,
           LATERAL FLATTEN (input => e."EVENT_PARAMS") f
),
/* pull ga_session_id and session_engaged flag for every event */
event_info AS (
    SELECT
        user_id,
        event_ts,
        MAX(CASE WHEN key_name = 'ga_session_id'
                 THEN int_val END)                                            AS ga_session_id,
        MAX(CASE WHEN key_name = 'session_engaged'
                 THEN COALESCE(int_val, TRY_TO_NUMBER(str_val)) END)          AS session_engaged
    FROM   event_params
    GROUP  BY user_id, event_ts
),
/* distinct sessions that are engaged (flag = 1) */
engaged_sessions AS (
    SELECT DISTINCT
           user_id,
           ga_session_id
    FROM   event_info
    WHERE  session_engaged = 1
           AND ga_session_id IS NOT NULL
),
/* count engaged sessions per user */
sessions_per_user AS (
    SELECT user_id,
           COUNT(*) AS engaged_session_cnt
    FROM   engaged_sessions
    GROUP  BY user_id
)
/* final average */
SELECT AVG(engaged_session_cnt)::FLOAT AS avg_engaged_sessions_per_user
FROM   sessions_per_user;