UNION ALL SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201231"
),
/* pull ga_session_id and session_engaged flag from every event              */
"EVENT_WITH_FLAGS" AS (
    SELECT
           d."USER_PSEUDO_ID",
           /* ga_session_id for the event                                    */
           MAX(
               CASE WHEN f.value:"key"::string = 'ga_session_id'
                    THEN f.value:"value":"int_value"::NUMBER
               END
           )                                                AS "GA_SESSION_ID",
           /* 1 if this event is marked as engaged                            */
           MAX(
               CASE WHEN f.value:"key"::string = 'session_engaged'
                    THEN COALESCE(
                             f.value:"value":"int_value"::NUMBER,
                             TRY_TO_NUMBER(f.value:"value":"string_value"::STRING)
                         )
               END
           )                                                AS "SESSION_ENGAGED_FLAG"
    FROM "DEC_EVENTS" d,
         LATERAL FLATTEN(INPUT => d."EVENT_PARAMS") f
    WHERE f.value:"key"::string IN ('ga_session_id','session_engaged')
    GROUP BY d."USER_PSEUDO_ID",              -- keep events distinct
             d."EVENT_TIMESTAMP"
),
/* keep only sessions where the flag is 1                                    */
"ENGAGED_SESSIONS" AS (
    SELECT DISTINCT
           "USER_PSEUDO_ID",
           "GA_SESSION_ID"
    FROM   "EVENT_WITH_FLAGS"
    WHERE  "SESSION_ENGAGED_FLAG" = 1
      AND  "GA_SESSION_ID"        IS NOT NULL
),
/* nb. of engaged sessions per user                                          */
"SESSION_COUNTS_PER_USER" AS (
    SELECT
           "USER_PSEUDO_ID",
           COUNT(DISTINCT "GA_SESSION_ID") AS "ENGAGED_SESSIONS"
    FROM   "ENGAGED_SESSIONS"
    GROUP BY "USER_PSEUDO_ID"
)
/*  final average                                                            */
SELECT
       ROUND(AVG("ENGAGED_SESSIONS"), 4) AS "AVG_ENGAGED_SESSIONS_PER_USER"
FROM   "SESSION_COUNTS_PER_USER";