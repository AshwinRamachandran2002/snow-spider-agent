    UNION ALL SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201231"
),

params_parsed AS (
    SELECT
        e."USER_PSEUDO_ID",
        e."EVENT_TIMESTAMP",
        /* -------- ga_session_id ---------- */
        MAX(
            CASE
                WHEN ep.value:key::STRING = 'ga_session_id' THEN
                     IFF(
                         ep.value:value:int_value IS NOT NULL,
                         ep.value:value:int_value,
                         TRY_TO_NUMBER(ep.value:value:string_value::STRING)
                     )
            END
        )::NUMBER                  AS ga_session_id,
        /* -------- session_engaged flag ---- */
        MAX(
            CASE
                WHEN ep.value:key::STRING = 'session_engaged' THEN
                     IFF(
                         ep.value:value:int_value IS NOT NULL,
                         ep.value:value:int_value,
                         TRY_TO_NUMBER(ep.value:value:string_value::STRING)
                     )
            END
        )::NUMBER                  AS session_engaged
    FROM dec_2020_events e,
         LATERAL FLATTEN ( INPUT => e."EVENT_PARAMS" ) ep
    GROUP BY e."USER_PSEUDO_ID", e."EVENT_TIMESTAMP"
),

engaged_sessions AS (
    SELECT DISTINCT
        "USER_PSEUDO_ID",
        ga_session_id
    FROM params_parsed
    WHERE session_engaged = 1
      AND ga_session_id IS NOT NULL
),

sessions_per_user AS (
    SELECT
        "USER_PSEUDO_ID",
        COUNT(*) AS engaged_sessions_per_user
    FROM engaged_sessions
    GROUP BY "USER_PSEUDO_ID"
)

SELECT
    AVG(engaged_sessions_per_user) AS avg_engaged_sessions_per_user
FROM sessions_per_user;