WITH dec_events AS (
    /* collect only the columns we need from every December-2020 daily table */
    SELECT "USER_PSEUDO_ID",
           "EVENT_NAME"
    FROM (
        TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201201"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201202"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201203"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201204"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201205"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201206"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201207"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201208"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201209"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201210"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201211"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201212"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201213"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201214"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201215"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201216"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201217"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201218"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201219"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201220"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201221"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201222"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201223"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201224"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201225"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201226"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201227"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201228"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201229"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201230"
        UNION ALL TABLE GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201231"
    )
),
user_stats AS (
    /* page-view count and purchase flag per user */
    SELECT
        "USER_PSEUDO_ID"                                 AS user_id,
        SUM(CASE WHEN "EVENT_NAME" = 'page_view' THEN 1 ELSE 0 END) AS pageviews,
        MAX(CASE WHEN "EVENT_NAME" = 'purchase'  THEN 1 ELSE 0 END) AS is_purchaser
    FROM dec_events
    GROUP BY "USER_PSEUDO_ID"
),
averages AS (
    SELECT
        AVG(CASE WHEN is_purchaser = 1 THEN pageviews END) AS purchaser_avg_pageviews,
        AVG(CASE WHEN is_purchaser = 0 THEN pageviews END) AS non_purchaser_avg_pageviews
    FROM user_stats
)
SELECT
    purchaser_avg_pageviews,
    non_purchaser_avg_pageviews,
    purchaser_avg_pageviews - non_purchaser_avg_pageviews AS avg_difference
FROM averages;