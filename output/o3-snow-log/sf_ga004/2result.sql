    SELECT
        "USER_PSEUDO_ID",
        SUM(CASE WHEN "EVENT_NAME" = 'page_view' THEN 1 ELSE 0 END)          AS pageviews,
        MAX(CASE WHEN "EVENT_NAME" IN ('purchase','in_app_purchase') THEN 1 ELSE 0 END) AS purchaser_flag
    FROM all_dec_events
    GROUP BY "USER_PSEUDO_ID"
)

SELECT
    AVG(CASE WHEN purchaser_flag = 1 THEN pageviews ELSE NULL END)  AS avg_pageviews_purchasers,
    AVG(CASE WHEN purchaser_flag = 0 THEN pageviews ELSE NULL END)  AS avg_pageviews_non_purchasers,
    AVG(CASE WHEN purchaser_flag = 1 THEN pageviews ELSE NULL END) -
    AVG(CASE WHEN purchaser_flag = 0 THEN pageviews ELSE NULL END)  AS avg_pageviews_difference
FROM user_metrics;