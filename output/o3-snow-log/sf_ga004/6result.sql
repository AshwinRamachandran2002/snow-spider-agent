    SELECT
        user_id,
        SUM(CASE WHEN event_name = 'page_view' THEN 1 ELSE 0 END) AS pageviews,
        MAX(CASE WHEN event_name = 'purchase'  THEN 1 ELSE 0 END) AS purchaser
    FROM union_events
    GROUP BY user_id
),

agg AS (
    SELECT
        AVG(CASE WHEN purchaser = 1 THEN pageviews END) AS avg_pageviews_purchasers,
        AVG(CASE WHEN purchaser = 0 THEN pageviews END) AS avg_pageviews_nonpurchasers
    FROM user_stats
)

SELECT
    ROUND(
        avg_pageviews_purchasers - avg_pageviews_nonpurchasers ,
        4
    ) AS "AVG_PAGEVIEW_DIFFERENCE"
FROM agg;