),
per_user AS (
    SELECT
        "USER_PSEUDO_ID"                                       AS user_id,
        SUM(CASE WHEN "EVENT_NAME" = 'page_view' THEN 1 ELSE 0 END) AS pageviews,
        MAX(CASE WHEN "EVENT_NAME" = 'purchase'  THEN 1 ELSE 0 END) AS purchased
    FROM dec_events
    GROUP BY "USER_PSEUDO_ID"
),
averages AS (
    SELECT
        AVG(CASE WHEN purchased = 1 THEN pageviews END) AS avg_purchasers,
        AVG(CASE WHEN purchased = 0 THEN pageviews END) AS avg_non_purchasers
    FROM per_user
)
SELECT
    ROUND(avg_purchasers - avg_non_purchasers, 4) AS avg_pageview_difference
FROM averages;