),

/* flatten hits → products and keep only completed-purchase products */
purchases AS (
    SELECT
        s."fullVisitorId"::STRING                           AS visitor_id,
        p.value:"v2ProductName"::STRING                     AS product_name,
        p.value:"productQuantity"::NUMBER                   AS product_qty
    FROM sessions_july                AS s,
         LATERAL FLATTEN(INPUT => PARSE_JSON(s."hits"))    AS h,
         LATERAL FLATTEN(INPUT => h.value:"product")       AS p
    WHERE p.value:"productQuantity"        IS NOT NULL
      AND h.value:"eCommerceAction":"action_type"::STRING = '6'   -- completed purchase
),

/* visitors who bought at least one YouTube-related product */
youtube_visitors AS (
    SELECT DISTINCT visitor_id
    FROM purchases
    WHERE LOWER(product_name) LIKE '%youtube%'
),

/* aggregate quantities for non-YouTube products bought by those visitors */
candidate_products AS (
    SELECT
        product_name,
        SUM(product_qty) AS total_qty
    FROM purchases
    WHERE visitor_id IN (SELECT visitor_id FROM youtube_visitors)
      AND LOWER(product_name) NOT LIKE '%youtube%'
    GROUP BY product_name
)

SELECT
    product_name,
    total_qty
FROM candidate_products
ORDER BY total_qty DESC NULLS LAST
LIMIT 1;