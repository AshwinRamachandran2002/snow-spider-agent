/* Find the non-YouTube product with the highest total quantity
   bought in July-2017 by visitors who purchased any YouTube item */
WITH july_sessions AS (
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170701" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170702" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170703" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170704" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170705" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170706" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170707" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170708" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170709" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170710" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170711" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170712" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170713" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170714" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170715" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170716" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170717" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170718" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170719" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170720" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170721" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170722" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170723" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170724" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170725" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170726" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170727" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170728" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170729" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170730" UNION ALL
    SELECT "fullVisitorId", "hits" FROM GA360.GOOGLE_ANALYTICS_SAMPLE."GA_SESSIONS_20170731"
),
hits_flat AS (
    SELECT
        js."fullVisitorId",
        h.value AS hit
    FROM july_sessions js,
         LATERAL FLATTEN(input => js."hits") h
),
products_flat AS (
    SELECT
        hf."fullVisitorId",
        p.value:"v2ProductName"::STRING  AS "product_name",
        p.value:"productQuantity"::INTEGER AS "product_qty"
    FROM hits_flat hf,
         LATERAL FLATTEN(input => hf.hit:"product") p
    WHERE p.value:"productQuantity" IS NOT NULL
      AND p.value:"productQuantity"::INTEGER > 0
),
visitors_with_yt AS (
    SELECT DISTINCT "fullVisitorId"
    FROM products_flat
    WHERE LOWER("product_name") LIKE '%youtube%'
)
SELECT
    "product_name",
    SUM("product_qty") AS "total_quantity"
FROM products_flat
WHERE "fullVisitorId" IN (SELECT "fullVisitorId" FROM visitors_with_yt)
  AND LOWER("product_name") NOT LIKE '%youtube%'
GROUP BY "product_name"
ORDER BY "total_quantity" DESC NULLS LAST
LIMIT 1;