/* Every purchased product (only hits with revenue) */
purchases AS (
    SELECT
        s."fullVisitorId"::STRING                    AS visitor_id,
        p.value:"v2ProductName"::STRING              AS product_name,
        COALESCE(p.value:"productQuantity"::NUMBER,1) AS quantity
    FROM july_sessions AS s,
         LATERAL FLATTEN(input => s."hits")  AS h,
         LATERAL FLATTEN(input => h.value:"product") AS p
    WHERE p.value:"productRevenue"::NUMBER IS NOT NULL     -- purchased items only
),

/* Visitors who bought at least one “YouTube” product */
visitors_youtube AS (
    SELECT DISTINCT visitor_id
    FROM purchases
    WHERE product_name ILIKE '%YouTube%'
)

/* Top non-YouTube product (by total qty) bought by those visitors */
SELECT
    product_name,
    SUM(quantity) AS total_quantity
FROM purchases
WHERE visitor_id IN (SELECT visitor_id FROM visitors_youtube)
  AND product_name NOT ILIKE '%YouTube%'
GROUP BY product_name
ORDER BY total_quantity DESC NULLS LAST
LIMIT 1;