    SELECT * FROM "GA360"."GOOGLE_ANALYTICS_SAMPLE"."GA_SESSIONS_20170731"
),

hits_expanded AS (           -- 2.  Expand to individual product rows
    SELECT
        s."fullVisitorId"::STRING                                          AS fullvisitorid,
        prod.value:"v2ProductName"::STRING                                 AS product_name,
        COALESCE(prod.value:"productQuantity"::NUMBER, 1)                 AS product_qty
    FROM july_sessions AS s,
         LATERAL FLATTEN(input => s."hits")   AS hit,
         LATERAL FLATTEN(input => hit.value:"product") AS prod
    WHERE prod.value:"productQuantity" IS NOT NULL
),

youtube_buyers AS (          -- 3.  Visitors who bought any YouTube-related product
    SELECT DISTINCT fullvisitorid
    FROM hits_expanded
    WHERE LOWER(product_name) LIKE '%youtube%'
),

non_yt_totals AS (           -- 4.  Totals for NON-YouTube products bought by those visitors
    SELECT
        product_name,
        SUM(product_qty) AS total_qty
    FROM hits_expanded
    WHERE fullvisitorid IN (SELECT fullvisitorid FROM youtube_buyers)
      AND LOWER(product_name) NOT LIKE '%youtube%'
    GROUP BY product_name
)

-- 5.  Highest-quantity non-YouTube product
SELECT product_name,
       total_qty
FROM non_yt_totals
ORDER BY total_qty DESC NULLS LAST
LIMIT 1;