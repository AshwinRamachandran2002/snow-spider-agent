),

products AS (
    SELECT
        s."fullVisitorId"                                    AS visitor_id,
        p.value:"v2ProductName"::STRING                      AS product_name,
        COALESCE(p.value:"productQuantity",1)::INTEGER       AS quantity
    FROM july_sessions AS s,
         LATERAL FLATTEN(input => s."hits")        h,
         LATERAL FLATTEN(input => h.value:"product") p
    WHERE p.value:"productQuantity" IS NOT NULL
),

youtube_visitors AS (
    SELECT DISTINCT visitor_id
    FROM products
    WHERE product_name ILIKE '%youtube%'                    -- visitor bought a YouTube-related product
      AND quantity > 0
)

SELECT
    product_name,
    SUM(quantity) AS total_quantity_purchased
FROM products
WHERE visitor_id IN (SELECT visitor_id FROM youtube_visitors) -- limit to those visitors
  AND product_name NOT ILIKE '%youtube%'                      -- exclude YouTube-named products
  AND quantity > 0
GROUP BY product_name
ORDER BY total_quantity_purchased DESC NULLS LAST
LIMIT 1;