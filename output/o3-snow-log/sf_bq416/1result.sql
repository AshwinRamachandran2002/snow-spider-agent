SELECT
    "BLOCK_NUMBER",
    "ARGS"::VARIANT[0]::STRING AS "FROM_ADDRESS",
    "ARGS"::VARIANT[1]::STRING AS "TO_ADDRESS",
    ("ARGS"::VARIANT[2]::NUMBER) / 1000000 AS "USDT_AMOUNT"
FROM "GOOG_BLOCKCHAIN"."GOOG_BLOCKCHAIN_ARBITRUM_ONE_US"."DECODED_EVENTS"
WHERE "EVENT_HASH" = '0xddf252ad1be2c89b69c2b068fc378daa952ba7f163c4a11628f55a4df523b3ef' -- Transfer
  AND LOWER("ADDRESS") = '0xfd086bc7cd5c481dcc9c85ebe478a1c0b69fcbb9' -- USDT on Arbitrum
ORDER BY "USDT_AMOUNT" DESC NULLS LAST
LIMIT 3;