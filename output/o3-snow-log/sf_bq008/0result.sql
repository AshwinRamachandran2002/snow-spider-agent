    UNION ALL SELECT * FROM GA360.GOOGLE_ANALYTICS_SAMPLE.GA_SESSIONS_20170131
),
hits_all AS (        --  every PAGE hit for the target campaign
    SELECT
        j."fullVisitorId",
        j."visitId",
        h.value:"hitNumber"::NUMBER            AS "hit_number",
        h.value:"page":"pagePath"::STRING      AS "page_path",
        h.value:"time"::NUMBER                 AS "hit_time"
    FROM jan17 j,
         LATERAL FLATTEN(input => j."hits") h
    WHERE j."trafficSource":"campaign"::STRING ILIKE '%Data%Share%'
      AND h.value:"type"::STRING = 'PAGE'
),
home_hits AS (       --  only the “/home*” hits, with look-ahead values
    SELECT
        *,
        LEAD("page_path") OVER (PARTITION BY "fullVisitorId","visitId"
                                ORDER BY "hit_number")                                AS "next_page",
        (LEAD("hit_time") OVER (PARTITION BY "fullVisitorId","visitId"
                                ORDER BY "hit_number") - "hit_time") / 1000           AS "time_on_home_sec"
    FROM hits_all
    WHERE "page_path" ILIKE '/home%'
)
--  final answer: most common next page + max seconds on “/home”
SELECT
    "next_page",
    COUNT(*)                 AS "visits_after_home",
    MAX("time_on_home_sec")  AS "max_time_on_home_sec"
FROM home_hits
WHERE "next_page" IS NOT NULL
GROUP BY "next_page"
ORDER BY "visits_after_home" DESC NULLS LAST
LIMIT 1;