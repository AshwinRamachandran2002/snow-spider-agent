WITH transfer_events AS (
    SELECT
        LOWER(PARSE_JSON("ARGS")[0]::STRING) AS "FROM_ADDRESS",
        LOWER(PARSE_JSON("ARGS")[1]::STRING) AS "TO_ADDRESS"
    FROM
        "GOOG_BLOCKCHAIN"."GOOG_BLOCKCHAIN_ARBITRUM_ONE_US"."DECODED_EVENTS"
    WHERE
        "EVENT_SIGNATURE" = 'Transfer(address,address,uint256)'
        AND "BLOCK_TIMESTAMP" >= 1672531200 * 1000000   -- since 2023-01-01 (µs)
)
SELECT
    CONCAT('https://cronoscan.com/address/', "FROM_ADDRESS") AS "SENDER_URL"
FROM
    transfer_events
WHERE
    "TO_ADDRESS" IS NOT NULL
    AND "TO_ADDRESS" <> '0x0000000000000000000000000000000000000000'
GROUP BY
    "SENDER_URL"
ORDER BY
    COUNT(*) DESC NULLS LAST
LIMIT 1;