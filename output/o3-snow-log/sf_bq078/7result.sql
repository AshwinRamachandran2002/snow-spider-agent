WITH "IMPC_ASSOCIATIONS" AS (
    SELECT DISTINCT "targetId"
    FROM OPEN_TARGETS_PLATFORM_2.OPEN_TARGETS_PLATFORM."ASSOCIATIONBYDATASOURCEINDIRECT"
    WHERE "diseaseId" = 'EFO_0000676'
      AND LOWER("datasourceId") = 'impc'
)
SELECT DISTINCT
       tgt."approvedSymbol"
FROM OPEN_TARGETS_PLATFORM_2.OPEN_TARGETS_PLATFORM."ASSOCIATIONBYOVERALLINDIRECT" ov
JOIN "IMPC_ASSOCIATIONS" impc
     ON ov."targetId" = impc."targetId"
JOIN OPEN_TARGETS_PLATFORM_2.OPEN_TARGETS_PLATFORM."TARGETS" tgt
     ON tgt."id" = ov."targetId"
WHERE ov."diseaseId" = 'EFO_0000676'
QUALIFY RANK() OVER (ORDER BY ov."score" DESC NULLS LAST) = 1;