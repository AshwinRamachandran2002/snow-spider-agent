/* ------------ first-open date per user ------------ */
first_open AS (
    SELECT 
        "user_pseudo_id",
        MIN("user_first_touch_timestamp") AS "uft_ts"
    FROM all_events
    GROUP BY "user_pseudo_id"
),

/* ------------ users whose first open is in Sep-2018 ------------ */
sept_users AS (
    SELECT
        "user_pseudo_id",
        "uft_ts",
        CAST(TO_TIMESTAMP("uft_ts"/1000000) AS DATE) AS "first_open_date"
    FROM first_open
    WHERE CAST(TO_TIMESTAMP("uft_ts"/1000000) AS DATE) BETWEEN '2018-09-01' AND '2018-09-30'
),

/* ------------ users who uninstalled within 7 days ------------ */
uninstalled AS (
    SELECT DISTINCT ae."user_pseudo_id"
    FROM all_events ae
    JOIN sept_users su
      ON ae."user_pseudo_id" = su."user_pseudo_id"
    WHERE ae."event_name" = 'app_remove'
      AND CAST(TO_TIMESTAMP(ae."event_timestamp"/1000000) AS DATE)
          <= su."first_open_date" + 7
),

/* ------------ among them, those who had a crash ------------ */
crashed AS (
    SELECT DISTINCT ae."user_pseudo_id"
    FROM all_events ae
    JOIN uninstalled u
      ON ae."user_pseudo_id" = u."user_pseudo_id"
    WHERE ae."event_name" = 'app_exception'
)

/* ------------ final percentage ------------ */
SELECT 
    ROUND(
        (SELECT COUNT(*) FROM crashed) * 100.0 
        / NULLIF((SELECT COUNT(*) FROM uninstalled),0),
        4
    ) AS "PERCENT_OF_UNINSTALLS_WITH_CRASH"
