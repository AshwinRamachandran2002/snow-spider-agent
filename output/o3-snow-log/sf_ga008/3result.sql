/* Users who completed at least one purchase in November 2020 */
purchase_users AS (
    SELECT DISTINCT "USER_PSEUDO_ID"
      FROM events_nov
     WHERE "EVENT_NAME" = 'purchase'
       AND "USER_PSEUDO_ID" IS NOT NULL
),

/* Page-view events generated by those purchasing users */
pageviews AS (
    SELECT "EVENT_DATE",
           "USER_PSEUDO_ID"
      FROM events_nov
     WHERE "EVENT_NAME"     = 'page_view'
       AND "USER_PSEUDO_ID" IN (SELECT "USER_PSEUDO_ID" FROM purchase_users)
)

SELECT
    "EVENT_DATE",
    COUNT(*)                                              AS "TOTAL_PAGE_VIEWS",
    ROUND( COUNT(*)::FLOAT / NULLIF(COUNT(DISTINCT "USER_PSEUDO_ID"),0) , 4 )
                                                         AS "AVG_PAGE_VIEWS_PER_USER"
FROM pageviews
GROUP BY "EVENT_DATE"
ORDER BY "EVENT_DATE" ASC;