    "EVENT_DATE",
    COUNT(*)                                           AS "TOTAL_PAGE_VIEWS",
    ROUND(COUNT(*)*1.0 / NULLIF(COUNT(DISTINCT "USER_PSEUDO_ID"),0),4) 
                                                     AS "AVG_PAGE_VIEWS_PER_USER"
FROM page_views
GROUP BY "EVENT_DATE"
