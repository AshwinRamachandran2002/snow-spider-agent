purchase_users AS (           -- ❷ users who purchased at least once in Nov-2020
    SELECT DISTINCT "USER_PSEUDO_ID"
    FROM nov_events 
    WHERE "EVENT_NAME" = 'purchase'
)
SELECT
    "EVENT_DATE",
    COUNT(*)                                 AS "TOTAL_PAGE_VIEWS",
    ROUND(COUNT(*)::FLOAT / NULLIF(COUNT(DISTINCT "USER_PSEUDO_ID"),0),4) 
                                             AS "AVG_PAGE_VIEWS_PER_USER"
FROM nov_events
WHERE "EVENT_NAME" = 'page_view'
  AND "USER_PSEUDO_ID" IN (SELECT "USER_PSEUDO_ID" FROM purchase_users)
GROUP BY "EVENT_DATE"
ORDER BY "EVENT_DATE";