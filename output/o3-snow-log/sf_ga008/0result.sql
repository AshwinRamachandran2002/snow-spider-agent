    UNION ALL SELECT "EVENT_DATE","EVENT_NAME","USER_PSEUDO_ID" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE.EVENTS_20201130
),
buyers AS (                     -- users who purchased at least once in Nov-2020
    SELECT DISTINCT "USER_PSEUDO_ID"
    FROM november_events
    WHERE "EVENT_NAME" = 'purchase'
),
page_views AS (                 -- page-view events generated by those buyers
    SELECT "EVENT_DATE",
           "USER_PSEUDO_ID"
    FROM november_events
    WHERE "EVENT_NAME" = 'page_view'
      AND "USER_PSEUDO_ID" IN (SELECT "USER_PSEUDO_ID" FROM buyers)
)
SELECT
    "EVENT_DATE"                                       AS "DATE",
    COUNT(*)                                           AS "TOTAL_PAGE_VIEWS",
    ROUND(COUNT(*)::FLOAT / COUNT(DISTINCT "USER_PSEUDO_ID"), 4)
                                                       AS "AVG_PAGE_VIEWS_PER_USER"
FROM page_views
GROUP BY "EVENT_DATE"
ORDER BY "EVENT_DATE";