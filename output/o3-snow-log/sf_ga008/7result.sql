/*------------------------------------------------------------------
  Identify every user who performed at least one 'purchase' event
  sometime during November-2020.
------------------------------------------------------------------*/
nov_purchasers AS (
    SELECT DISTINCT "USER_PSEUDO_ID"
    FROM   nov_events
    WHERE  "EVENT_NAME" = 'purchase'
)
/*------------------------------------------------------------------
  Compute daily totals and per-user averages for 'page_view' events
  generated ONLY by November purchasers.
------------------------------------------------------------------*/
SELECT
    "EVENT_DATE",
    COUNT(*)                               AS "TOTAL_PAGE_VIEWS",
    COUNT(*)::FLOAT / NULLIF(COUNT(DISTINCT "USER_PSEUDO_ID"),0)
                                            AS "AVG_PAGE_VIEWS_PER_USER"
FROM   nov_events
WHERE  "EVENT_NAME" = 'page_view'
  AND  "USER_PSEUDO_ID" IN (SELECT "USER_PSEUDO_ID" FROM nov_purchasers)
GROUP BY "EVENT_DATE"
ORDER BY "EVENT_DATE";