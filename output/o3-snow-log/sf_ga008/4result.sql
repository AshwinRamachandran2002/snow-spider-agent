        SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201129" UNION ALL
        SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20201130"
),

/* ------------------------------------------------------------------
   Users who made at least one purchase in November-2020
------------------------------------------------------------------ */
purchasers AS (
    SELECT DISTINCT "USER_PSEUDO_ID"
    FROM nov_events
    WHERE "EVENT_NAME" = 'purchase'
),

/* ------------------------------------------------------------------
   Page-view events generated by November purchasers
------------------------------------------------------------------ */
pageviews AS (
    SELECT
        "EVENT_DATE",
        "USER_PSEUDO_ID"
    FROM nov_events
    WHERE "EVENT_NAME" = 'page_view'
      AND "USER_PSEUDO_ID" IN (SELECT "USER_PSEUDO_ID" FROM purchasers)
)

/* ------------------------------------------------------------------
   Final aggregation – total PVs and average PVs per purchasing user
------------------------------------------------------------------ */
SELECT
    TO_DATE("EVENT_DATE", 'YYYYMMDD')                                 AS "DATE",
    COUNT(*)                                                          AS "TOTAL_PAGE_VIEWS",
    ROUND(
          COUNT(*)::FLOAT
          / NULLIF(COUNT(DISTINCT "USER_PSEUDO_ID"), 0), 4)           AS "AVG_PAGE_VIEWS_PER_USER"
FROM pageviews
GROUP BY "EVENT_DATE"
ORDER BY "DATE" NULLS LAST;