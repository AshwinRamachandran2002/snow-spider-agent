WITH events_7d AS (   -- 01-Jan-2021 00:00:00  →  07-Jan-2021 23:59:59
    SELECT "USER_PSEUDO_ID","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210101"
    UNION ALL
    SELECT "USER_PSEUDO_ID","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210102"
    UNION ALL
    SELECT "USER_PSEUDO_ID","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210103"
    UNION ALL
    SELECT "USER_PSEUDO_ID","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210104"
    UNION ALL
    SELECT "USER_PSEUDO_ID","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210105"
    UNION ALL
    SELECT "USER_PSEUDO_ID","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210106"
    UNION ALL
    SELECT "USER_PSEUDO_ID","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210107"
),
positive_7d AS (
    SELECT DISTINCT e."USER_PSEUDO_ID"
    FROM events_7d e,
         LATERAL FLATTEN(input => e."EVENT_PARAMS") p
    WHERE p.value:"key"::STRING = 'engagement_time_msec'
      AND p.value:"value":"int_value"::NUMBER > 0      -- positive engagement time
),
events_2d AS (   -- 06-Jan-2021 00:00:00  →  07-Jan-2021 23:59:59
    SELECT "USER_PSEUDO_ID","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210106"
    UNION ALL
    SELECT "USER_PSEUDO_ID","EVENT_PARAMS" FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210107"
),
positive_2d AS (
    SELECT DISTINCT e."USER_PSEUDO_ID"
    FROM events_2d e,
         LATERAL FLATTEN(input => e."EVENT_PARAMS") p
    WHERE p.value:"key"::STRING = 'engagement_time_msec'
      AND p.value:"value":"int_value"::NUMBER > 0
)
SELECT COUNT(*) AS "DISTINCT_USERS"
FROM positive_7d
WHERE "USER_PSEUDO_ID" NOT IN (SELECT "USER_PSEUDO_ID" FROM positive_2d);