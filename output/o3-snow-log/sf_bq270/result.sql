/*-----------------------------------------------------------
   explode hits  ->  products, keep only non-impression
------------------------------------------------------------*/
product_events AS
(
    SELECT
        TO_DATE(s."date",'YYYYMMDD')                       AS session_date ,
        DATE_TRUNC('month', TO_DATE(s."date",'YYYYMMDD'))  AS month_start ,
        /* classify the product-level event */
        CASE hit.value:"eCommerceAction":"action_type"::STRING
             WHEN '2' THEN 'detail'
             WHEN '3' THEN 'add_to_cart'
             WHEN '6' THEN 'purchase'
        END                                               AS event_type
    FROM sessions                s
         , LATERAL FLATTEN(input => s."hits")             hit
         , LATERAL FLATTEN(input => hit.value:"product")  prod
    WHERE prod.value IS NOT NULL
      AND ( prod.value:"isImpression"::BOOLEAN IS NULL
            OR prod.value:"isImpression"::BOOLEAN = FALSE )
      AND hit.value:"eCommerceAction":"action_type"::STRING IN ('2','3','6')
)
/*-----------------------------------------------------------
  aggregate & calculate conversion rates
------------------------------------------------------------*/
SELECT
    TO_CHAR(month_start,'YYYY-MM')                                                            AS "MONTH" ,
    ROUND( 100 * SUM( CASE WHEN event_type='add_to_cart' THEN 1 ELSE 0 END )
               / NULLIF( SUM( CASE WHEN event_type='detail'     THEN 1 ELSE 0 END ), 0 )
         , 4)                                                                                 AS "ADD_TO_CART_RATE_PCT" ,
    ROUND( 100 * SUM( CASE WHEN event_type='purchase'   THEN 1 ELSE 0 END )
               / NULLIF( SUM( CASE WHEN event_type='detail'     THEN 1 ELSE 0 END ), 0 )
         , 4)                                                                                 AS "PURCHASE_RATE_PCT"
FROM product_events
GROUP BY month_start
ORDER BY month_start;