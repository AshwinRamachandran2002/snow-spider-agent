/* --------------- installs in Aug–Sep 2018 --------------- */
INSTALLS AS
(
    SELECT
        "user_pseudo_id",
        MIN("event_timestamp") AS install_ts
    FROM ALL_EVENTS
    WHERE "event_name" = 'first_open'
      AND TO_DATE( TO_TIMESTAMP("event_timestamp" / 1000000) )
          BETWEEN '2018-08-01' AND '2018-09-30'
    GROUP BY "user_pseudo_id"
),

/* --------------- first uninstall (if any) --------------- */
UNINSTALLS AS
(
    SELECT
        "user_pseudo_id",
        MIN("event_timestamp") AS uninstall_ts
    FROM ALL_EVENTS
    WHERE "event_name" = 'app_remove'      -- Firebase uninstall event
    GROUP BY "user_pseudo_id"
),

/* --------------- flag whether user uninstalled within 7 days --------------- */
RETENTION AS
(
    SELECT
        i."user_pseudo_id",
        CASE
            WHEN u.uninstall_ts IS NULL                               THEN 1      -- never uninstalled
            WHEN u.uninstall_ts - i.install_ts > 7*24*60*60*1000000   THEN 1      -- uninstalled, but after 7 days
            ELSE 0
        END AS retained_flag
    FROM INSTALLS i
    LEFT JOIN UNINSTALLS u
           ON i."user_pseudo_id" = u."user_pseudo_id"
)

/* --------------- final percentage --------------- */
SELECT
    ROUND( (SUM(retained_flag) * 100.0) / COUNT(*), 4) AS pct_users_retained_7d_or_never_uninstalled
FROM RETENTION;