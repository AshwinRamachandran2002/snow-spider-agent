/*  installs that occurred during August-September 2018  */
"INSTALLS" AS (
    SELECT  "user_pseudo_id",
            MIN("user_first_touch_timestamp") AS "first_touch_ts"
    FROM    "EVENTS"
    GROUP BY "user_pseudo_id"
    HAVING  TO_TIMESTAMP_NTZ("first_touch_ts"/1000000)
                BETWEEN '2018-08-01' AND '2018-09-30 23:59:59'
),

/*  earliest uninstall (app_remove) for those users  */
"UNINSTALL" AS (
    SELECT  e."user_pseudo_id",
            MIN(e."event_timestamp") AS "uninstall_ts"
    FROM    "EVENTS" e
            JOIN "INSTALLS" i
              ON e."user_pseudo_id" = i."user_pseudo_id"
    WHERE   e."event_name" = 'app_remove'
    GROUP BY e."user_pseudo_id"
),

/*  flag users who did NOT uninstall within 7 days (or never)  */
"SUMMARY" AS (
    SELECT  i."user_pseudo_id",
            i."first_touch_ts",
            u."uninstall_ts",
            CASE 
                WHEN u."uninstall_ts" IS NULL                                  THEN 1       -- never uninstalled
                WHEN u."uninstall_ts" - i."first_touch_ts" > 604800000000      THEN 1       -- uninstalled after 7 days
                ELSE 0
            END AS "kept_7_days"
    FROM    "INSTALLS" i
            LEFT JOIN "UNINSTALL" u
              ON i."user_pseudo_id" = u."user_pseudo_id"
)

/*  final percentage  */
SELECT  ROUND( (SUM("kept_7_days") * 100.0) / COUNT(*), 4 ) 
        AS "PCT_USERS_NOT_UNINSTALL_WITHIN_7_DAYS"
FROM    "SUMMARY";