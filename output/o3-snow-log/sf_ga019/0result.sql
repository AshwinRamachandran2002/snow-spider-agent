/* --------------  first time the app was opened (install time) -------------- */
installs AS (
    SELECT 
        "user_pseudo_id",
        MIN("user_first_touch_timestamp") AS install_ts_micro
    FROM union_events
    GROUP BY "user_pseudo_id"
),

/* --------------  keep installs that happened Aug-Sep 2018 -------------- */
installs_aug_sep AS (
    SELECT *
    FROM installs
    WHERE install_ts_micro >= 1533081600000000   -- 2018-08-01 00:00:00 UTC
      AND install_ts_micro <  1538352000000000   -- 2018-10-01 00:00:00 UTC
),

/* --------------  first uninstall (app_remove) for those users -------------- */
uninstalls AS (
    SELECT 
        ue."user_pseudo_id",
        MIN(ue."event_timestamp") AS uninstall_ts_micro
    FROM union_events ue
    JOIN installs_aug_sep ia
      ON ia."user_pseudo_id" = ue."user_pseudo_id"
    WHERE ue."event_name" = 'app_remove'
    GROUP BY ue."user_pseudo_id"
),

/* --------------  classify each user as retained >7d or never uninstalled -------------- */
final AS (
    SELECT 
        ia."user_pseudo_id",
        ia.install_ts_micro,
        u.uninstall_ts_micro,
        CASE 
            WHEN u.uninstall_ts_micro IS NULL                                        THEN 1   -- never uninstalled
            WHEN (u.uninstall_ts_micro - ia.install_ts_micro) > 604800000000         THEN 1   -- uninstalled after 7 days
            ELSE 0                                                                       END AS retained_flag
    FROM installs_aug_sep ia
    LEFT JOIN uninstalls u
      ON ia."user_pseudo_id" = u."user_pseudo_id"
)

/* ----------------------  final percentage calculation  --------------------- */
SELECT 
    ROUND( (SUM(retained_flag) * 100.0) / COUNT(*), 4 ) AS "PERCENT_USERS_NO_UNINSTALL_WITHIN_7D"
FROM final;