/* Users whose very first install happened in Aug-Sep 2018 */
installs AS (
    SELECT
        "user_pseudo_id",
        MIN("user_first_touch_timestamp") AS first_touch_ts
    FROM all_events
    GROUP BY "user_pseudo_id"
    HAVING TO_DATE(TO_TIMESTAMP_LTZ(first_touch_ts/1000000)) BETWEEN '2018-08-01' AND '2018-09-30'
),

/* First uninstall (if any) for each user */
uninstalls AS (
    SELECT
        "user_pseudo_id",
        MIN("event_timestamp") AS uninstall_ts
    FROM all_events
    WHERE "event_name" = 'app_remove'
    GROUP BY "user_pseudo_id"
),

/* Flag users who did NOT uninstall within 7 days (or never uninstalled) */
combined AS (
    SELECT
        i."user_pseudo_id",
        i.first_touch_ts,
        u.uninstall_ts,
        CASE
            WHEN u.uninstall_ts IS NULL                                          THEN 1  -- never uninstalled
            WHEN (u.uninstall_ts - i.first_touch_ts) > 604800000000              THEN 1  -- uninstalled after 7 days
            ELSE 0                                                                 END  AS kept_flag
    FROM installs i
    LEFT JOIN uninstalls u
           ON i."user_pseudo_id" = u."user_pseudo_id"
)

/* Final percentage */
SELECT
    ROUND(100.0 * SUM(kept_flag) / COUNT(*), 4) AS "PERCENT_DID_NOT_UNINSTALL_WITHIN_7_DAYS_OR_NEVER"
FROM combined;