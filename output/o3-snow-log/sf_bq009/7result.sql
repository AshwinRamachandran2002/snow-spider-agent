parsed AS (
    SELECT
        ("trafficSource":"source")::STRING            AS src,
        ("totals":"totalTransactionRevenue")::NUMBER  AS revenue,
        TO_CHAR(TO_DATE("date",'YYYYMMDD'),'YYYY-MM') AS ym
    FROM sessions_2017
),
filtered AS (
    SELECT *
    FROM parsed
    WHERE revenue IS NOT NULL
      AND src     IS NOT NULL
),
yearly AS (
    SELECT src,
           SUM(revenue) AS year_rev
    FROM filtered
    GROUP BY src
),
top_src AS (
    SELECT src
    FROM yearly
    ORDER BY year_rev DESC NULLS LAST
    LIMIT 1
),
monthly AS (
    SELECT ym,
           SUM(revenue) AS month_rev
    FROM filtered f
    JOIN top_src t  ON f.src = t.src
    GROUP BY ym
)

SELECT t.src                                              AS "traffic_source",
       ROUND( (MAX(month_rev) - MIN(month_rev)) / 1e6 , 2) AS "difference_in_millions"
FROM   monthly, top_src t
