    UNION ALL SELECT * FROM GA360.GOOGLE_ANALYTICS_SAMPLE.GA_SESSIONS_20170731
),
/*  Customers who bought the Henley in July-2017                    */
customers AS (
    SELECT DISTINCT s."fullVisitorId"
    FROM   july_sessions               s,
           LATERAL FLATTEN(input => s."hits")            h,
           LATERAL FLATTEN(input => h.value:"product")   p
    WHERE  LOWER(p.value:"v2ProductName"::string) LIKE '%youtube%'
      AND  LOWER(p.value:"v2ProductName"::string) LIKE '%vintage%'
      AND  LOWER(p.value:"v2ProductName"::string) LIKE '%henley%'
      AND  COALESCE(p.value:"productRevenue"::INTEGER ,0) > 0    -- bought, not just viewed
)
/*  All other products these customers purchased, ranked by revenue */
SELECT
       p.value:"v2ProductName"::string                        AS product_name ,
       SUM( COALESCE(p.value:"productRevenue"::INTEGER ,0) )  AS total_revenue ,
       SUM( COALESCE(p.value:"productQuantity"::INTEGER ,0) ) AS total_quantity
FROM   july_sessions              s
JOIN   customers                  c   ON s."fullVisitorId" = c."fullVisitorId"
     , LATERAL FLATTEN(input => s."hits")          h
     , LATERAL FLATTEN(input => h.value:"product") p
WHERE  NOT (
           LOWER(p.value:"v2ProductName"::string) LIKE '%youtube%'
       AND LOWER(p.value:"v2ProductName"::string) LIKE '%vintage%'
       AND LOWER(p.value:"v2ProductName"::string) LIKE '%henley%'
      )
GROUP  BY product_name
ORDER  BY total_revenue DESC NULLS LAST
LIMIT  1;