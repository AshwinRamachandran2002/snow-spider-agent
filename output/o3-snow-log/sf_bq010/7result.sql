    SELECT * FROM GA360.GOOGLE_ANALYTICS_SAMPLE.GA_SESSIONS_20170731
),

buyers AS (
    /* customers who purchased “YouTube Men’s Vintage Henley” */
    SELECT DISTINCT
           js."fullVisitorId"
    FROM   july_sessions js,
           LATERAL FLATTEN(input => js."hits")      hit,
           LATERAL FLATTEN(input => hit.value:"product")  prod
    WHERE  COALESCE(prod.value:"productRevenue",0)::NUMBER > 0
      AND  prod.value:"v2ProductName"::STRING ILIKE '%Vintage%Henley%'
),

buyer_sales AS (
    /* all other products these customers bought in July 2017 */
    SELECT
        prod.value:"v2ProductName"::STRING                                   AS product_name,
        SUM(COALESCE(prod.value:"productRevenue",0)::NUMBER)                AS total_revenue
    FROM   july_sessions js
    JOIN   buyers b
           ON js."fullVisitorId" = b."fullVisitorId",
           LATERAL FLATTEN(input => js."hits")      hit,
           LATERAL FLATTEN(input => hit.value:"product")  prod
    WHERE  COALESCE(prod.value:"productRevenue",0)::NUMBER > 0
      AND  prod.value:"v2ProductName"::STRING NOT ILIKE '%Vintage%Henley%'
    GROUP BY product_name
)

SELECT product_name,
       total_revenue
FROM   buyer_sales
ORDER BY total_revenue DESC NULLS LAST
LIMIT 1;