    SELECT * FROM GA360.GOOGLE_ANALYTICS_SAMPLE.GA_SESSIONS_20170731
),
/* explode hits  ➜  products purchased */
july_products AS (
    SELECT
        s."fullVisitorId"                               AS visitor_id,
        p.value:"v2ProductName"::string                 AS product_name,
        COALESCE(p.value:"productQuantity",1)::number   AS qty
    FROM july_sessions            AS s
         ,LATERAL FLATTEN(input => s."hits")           AS h
         ,LATERAL FLATTEN(input => h.value:"product") AS p
    WHERE p.value:"v2ProductName" IS NOT NULL
),
/* visitors who bought the target product */
target_buyers AS (
    SELECT DISTINCT visitor_id
    FROM july_products
    WHERE LOWER(product_name) LIKE '%vintage%henley%'
),
/* products those visitors bought (excluding the target one) */
other_sales AS (
    SELECT
        product_name,
        SUM(qty) AS total_qty
    FROM july_products
    WHERE visitor_id IN (SELECT visitor_id FROM target_buyers)
      AND LOWER(product_name) NOT LIKE '%vintage%henley%'
    GROUP BY product_name
)
/* top-selling companion product */
SELECT product_name,
       total_qty
FROM other_sales
ORDER BY total_qty DESC NULLS LAST
LIMIT 1;