/* 1. Visitors who bought “YouTube Men’s Vintage Henley” (completed purchase) */
henley_buyers AS (
    SELECT DISTINCT s."fullVisitorId"
    FROM july_sessions      AS s,
         LATERAL FLATTEN(input => s."hits")        AS h,
         LATERAL FLATTEN(input => h.value:"product") AS p
    WHERE  LOWER(p.value:"v2ProductName"::STRING)     LIKE '%vintage henley%'
      AND  LOWER(p.value:"v2ProductName"::STRING)     LIKE '%youtube%'
      AND  h.value:"eCommerceAction":"action_type"::STRING = '6'   -- completed purchase
),

/* 2. Products bought by those visitors (excluding the Henley itself) */
other_products AS (
    SELECT
        p.value:"v2ProductName"::STRING                         AS product_name,
        COALESCE(SUM(p.value:"productQuantity"::NUMBER), 0)     AS total_qty
    FROM july_sessions   AS s
    JOIN henley_buyers   AS b   ON b."fullVisitorId" = s."fullVisitorId"
         , LATERAL FLATTEN(input => s."hits")        AS h
         , LATERAL FLATTEN(input => h.value:"product") AS p
    WHERE  h.value:"eCommerceAction":"action_type"::STRING = '6'
      AND  LOWER(p.value:"v2ProductName"::STRING) NOT LIKE '%vintage henley%'
    GROUP BY product_name
)

/* 3. Top-selling product */
SELECT product_name,
       total_qty
FROM   other_products
ORDER  BY total_qty DESC NULLS LAST
LIMIT  1;