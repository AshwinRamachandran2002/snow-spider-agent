    SELECT * FROM GA360.GOOGLE_ANALYTICS_SAMPLE.GA_SESSIONS_20170731
),

/* visitors who completed a purchase that contained
   the product “YouTube … Vintage Henley” */
henley_buyers AS (
    SELECT DISTINCT s."fullVisitorId"
    FROM july_sessions           AS s
         ,LATERAL FLATTEN(input => s."hits")          AS h
         ,LATERAL FLATTEN(input => h.value:"product") AS p
    WHERE h.value:"eCommerceAction":"action_type"::string = '6'        -- completed purchase
      AND p.value:"v2ProductName"::string ILIKE '%youtube%vintage%henley%'
),

/* all other products bought by those visitors, with quantities */
buyer_products AS (
    SELECT
        p.value:"v2ProductName"::string                                      AS product_name ,
        SUM(COALESCE(TRY_TO_NUMBER(p.value:"productQuantity"::string),1))    AS total_qty
    FROM july_sessions  AS s
    JOIN henley_buyers  AS b
      ON s."fullVisitorId" = b."fullVisitorId"
         ,LATERAL FLATTEN(input => s."hits")          AS h
         ,LATERAL FLATTEN(input => h.value:"product") AS p
    WHERE h.value:"eCommerceAction":"action_type"::string = '6'              -- completed purchase
      AND p.value:"v2ProductName"::string NOT ILIKE '%youtube%vintage%henley%'  -- exclude Henley
    GROUP BY product_name
)

/* pick the top-selling product */
SELECT product_name ,
       total_qty
FROM (
    SELECT product_name ,
           total_qty ,
           ROW_NUMBER() OVER (ORDER BY total_qty DESC NULLS LAST) AS rn
    FROM buyer_products
)
WHERE rn = 1;