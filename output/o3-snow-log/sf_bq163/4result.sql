SELECT
    "FEATURE_NAME",
    AVG(CASE WHEN "SEX" = 'female' THEN "X_VALUE" END) AS "FEMALE_AVG",
    AVG(CASE WHEN "SEX" = 'male'   THEN "X_VALUE" END) AS "MALE_AVG",
    AVG(CASE WHEN "SEX" = 'female' THEN "X_VALUE" END) 
      - AVG(CASE WHEN "SEX" = 'male' THEN "X_VALUE" END) AS "DIFF_FEMALE_MINUS_MALE"
FROM
    HTAN_2.HTAN.SCRNASEQ_MSK_SCLC_COMBINED_SAMPLES_CURRENT
WHERE
    "CELL_TYPE_COARSE"  = 'Epithelial'
    AND "CLUSTERS"      = '41'
    AND "DEVELOPMENT_STAGE" = '74-year-old human stage'
GROUP BY
    "FEATURE_NAME"
HAVING
    "FEMALE_AVG" IS NOT NULL
    AND "MALE_AVG"   IS NOT NULL
ORDER BY
    "DIFF_FEMALE_MINUS_MALE" DESC NULLS LAST
LIMIT 20;