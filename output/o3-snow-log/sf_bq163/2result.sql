SELECT
    "FEATURE_NAME",
    ROUND(AVG(CASE WHEN "SEX" = 'female' THEN "X_VALUE" END), 4)   AS "FEMALE_AVG",
    ROUND(AVG(CASE WHEN "SEX" = 'male'   THEN "X_VALUE" END), 4)   AS "MALE_AVG",
    ROUND(
        AVG(CASE WHEN "SEX" = 'female' THEN "X_VALUE" END) -
        AVG(CASE WHEN "SEX" = 'male'   THEN "X_VALUE" END), 4
    ) AS "DIFF_F_MINUS_M"
FROM "HTAN_2"."HTAN"."SCRNASEQ_MSK_SCLC_COMBINED_SAMPLES_CURRENT"
WHERE
    "CELL_TYPE_COARSE" = 'Epithelial'
    AND "CLUSTERS" = '41'
    AND "DEVELOPMENT_STAGE" = '74-year-old human stage'
    AND "SEX" IN ('female', 'male')
GROUP BY
    "FEATURE_NAME"
HAVING
    AVG(CASE WHEN "SEX" = 'female' THEN "X_VALUE" END) IS NOT NULL
    AND AVG(CASE WHEN "SEX" = 'male'   THEN "X_VALUE" END) IS NOT NULL
ORDER BY
    "DIFF_F_MINUS_M" DESC NULLS LAST
LIMIT 20;