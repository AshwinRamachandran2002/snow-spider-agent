page_events AS (
    SELECT
        e."USER_PSEUDO_ID"                                   AS user_id,
        f.value:"value":"string_value"::string               AS page_location
    FROM all_events e,
         LATERAL FLATTEN ( input => e."EVENT_PARAMS" ) f
    WHERE e."EVENT_NAME" = 'page_view'
      AND f.value:"key"::string = 'page_location'
), 

most_viewed_page AS (                              
    SELECT page_location
    FROM page_events
    GROUP BY page_location
    ORDER BY COUNT(*) DESC NULLS LAST
    LIMIT 1
)

SELECT COUNT(DISTINCT user_id) AS distinct_user_count
FROM page_events
WHERE page_location = ( SELECT page_location FROM most_viewed_page );