page_views AS (   -- extract page_location for page_view events
    SELECT
        je."USER_PSEUDO_ID"        AS user_id,
        ep.value:"string_value"::string AS page_location
    FROM jan_events je,
         LATERAL FLATTEN(input => je."EVENT_PARAMS") ep
    WHERE je."EVENT_NAME" = 'page_view'
      AND ep.value:key::string = 'page_location'
      AND ep.value:"string_value" IS NOT NULL
),
most_visited_page AS (      -- find the most visited page_location
    SELECT page_location
    FROM (
        SELECT page_location,
               COUNT(*) AS pageviews
        FROM page_views
        GROUP BY page_location
        ORDER BY pageviews DESC NULLS LAST
        LIMIT 1
    )
)
SELECT COUNT(DISTINCT user_id) AS distinct_users
FROM   page_views
JOIN   most_visited_page USING (page_location);