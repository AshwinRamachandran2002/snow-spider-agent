        SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210128" UNION ALL
        SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210129" UNION ALL
        SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210130" UNION ALL
        SELECT * FROM GA4.GA4_OBFUSCATED_SAMPLE_ECOMMERCE."EVENTS_20210131"
    )
),
page_counts AS (          -- page_view counts per page_location
    SELECT
        ep.value:"string_value"::string AS page_location,
        COUNT(*)                       AS page_views
    FROM january_events je,
         LATERAL FLATTEN(input => je."EVENT_PARAMS") ep
    WHERE je."EVENT_NAME" = 'page_view'
      AND ep.value:"key"::string = 'page_location'
    GROUP BY page_location
),
top_page AS (             -- most-visited page in January
    SELECT page_location
    FROM page_counts
    ORDER BY page_views DESC NULLS LAST
    LIMIT 1
),
users_on_top_page AS (    -- distinct users that saw that page
    SELECT DISTINCT je."USER_PSEUDO_ID"
    FROM january_events je,
         LATERAL FLATTEN(input => je."EVENT_PARAMS") ep
    WHERE je."EVENT_NAME" = 'page_view'
      AND ep.value:"key"::string = 'page_location'
      AND ep.value:"string_value"::string IN (SELECT page_location FROM top_page)
)
SELECT COUNT(*) AS "DISTINCT_USERS_VIEWED_TOP_PAGE"
FROM users_on_top_page;