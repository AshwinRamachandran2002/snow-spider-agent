page_views AS (               -- isolate every page_view with its URL
    SELECT
        ep.value:"string_value"::string AS page_location,
        ev."USER_PSEUDO_ID"
    FROM all_events ev,
         LATERAL FLATTEN (input => ev."EVENT_PARAMS") ep
    WHERE ev."EVENT_NAME" = 'page_view'
      AND ep.value:"key"::string = 'page_location'
),
top_page AS (                 -- most frequently visited page in the month
    SELECT page_location
    FROM (
        SELECT page_location,
               COUNT(*) AS views
        FROM page_views
        GROUP BY page_location
        ORDER BY views DESC NULLS LAST
        LIMIT 1
    )
)
SELECT COUNT(DISTINCT pv."USER_PSEUDO_ID") AS distinct_users_viewing_top_page
FROM   page_views pv
JOIN   top_page tp
       ON pv.page_location = tp.page_location;