),
/* --------  isolate page-view events and grab the URL (page_location)  -------- */
page_views AS (
    SELECT
        je."USER_PSEUDO_ID"                                        AS user_id,
        fv.value:"string_value"::string                            AS page_location
    FROM jan_events je,
         LATERAL FLATTEN( INPUT => je."EVENT_PARAMS" ) fv
    WHERE je."EVENT_NAME" = 'page_view'
      AND fv.value:"key"::string = 'page_location'
),
/* --------  find the single most visited page in January  -------- */
top_page AS (
    SELECT page_location
    FROM page_views
    GROUP BY page_location
    ORDER BY COUNT(*) DESC NULLS LAST
    LIMIT 1
)
/* --------  count distinct users who viewed that page  -------- */
SELECT COUNT( DISTINCT pv.user_id ) AS distinct_users
FROM   page_views pv
JOIN   top_page  tp
  ON   pv.page_location = tp.page_location;