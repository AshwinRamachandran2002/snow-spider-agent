page_views AS (
    /* isolate page_location from page_view events */
    SELECT
        FLATTENED.value:"value":"string_value"::string        AS page_location,
        ue."USER_PSEUDO_ID"                                  AS user_id
    FROM union_events ue,
         LATERAL FLATTEN(input => ue."EVENT_PARAMS") AS FLATTENED
    WHERE ue."EVENT_NAME" = 'page_view'
      AND FLATTENED.value:"key"::string = 'page_location'
      AND FLATTENED.value:"value":"string_value" IS NOT NULL
),

page_counts AS (
    SELECT page_location,
           COUNT(*) AS view_cnt
    FROM page_views
    GROUP BY page_location
),

top_page AS (
    SELECT page_location
    FROM page_counts
    ORDER BY view_cnt DESC NULLS LAST
    LIMIT 1
)

SELECT COUNT(DISTINCT pv.user_id) AS distinct_users
FROM page_views pv
JOIN top_page tp
  ON pv.page_location = tp.page_location;