/* -----------------------------------------------------------
   2. Pick purchase events, pull session-id & revenue
------------------------------------------------------------*/
purchases AS (
    SELECT
        ue."USER_PSEUDO_ID",
        -- extract ga_session_id from event_params array
        f.value:"value":"int_value"::NUMBER            AS GA_SESSION_ID,
        -- extract purchase revenue from ecommerce record
        ue."ECOMMERCE":"purchase_revenue_in_usd"::FLOAT AS PURCHASE_REVENUE_USD
    FROM union_events  ue
    ,    LATERAL FLATTEN(input => ue."EVENT_PARAMS") f
    WHERE ue."EVENT_NAME" = 'purchase'
      AND f.value:"key"::STRING = 'ga_session_id'
      AND ue."ECOMMERCE":"purchase_revenue_in_usd" IS NOT NULL
),
/* -----------------------------------------------------------
   3. Revenue per session (sum in case multiple purchase events)
------------------------------------------------------------*/
session_revenue AS (
    SELECT
        "USER_PSEUDO_ID",
        GA_SESSION_ID,
        SUM(PURCHASE_REVENUE_USD) AS SESSION_REVENUE_USD
    FROM purchases
    GROUP BY "USER_PSEUDO_ID", GA_SESSION_ID
),
/* -----------------------------------------------------------
   4. Average revenue per purchasing session; keep users
      with >1 purchase session
------------------------------------------------------------*/
user_metrics AS (
    SELECT
        "USER_PSEUDO_ID",
        COUNT(*)                                       AS PURCHASE_SESSIONS,
        AVG(SESSION_REVENUE_USD)                       AS AVG_PURCHASE_REVENUE_USD_PER_SESSION
    FROM session_revenue
    GROUP BY "USER_PSEUDO_ID"
    HAVING PURCHASE_SESSIONS > 1
)
/* -----------------------------------------------------------
   5. Final output
------------------------------------------------------------*/
SELECT
    "USER_PSEUDO_ID",
    ROUND(AVG_PURCHASE_REVENUE_USD_PER_SESSION, 4) AS AVG_PURCHASE_REVENUE_USD_PER_SESSION
FROM user_metrics
ORDER BY AVG_PURCHASE_REVENUE_USD_PER_SESSION DESC NULLS LAST;