SELECT
    CAST(TO_TIMESTAMP_NTZ("TIME") AS DATE)            AS "SESSION_START_DATE",
    "APP_GROUP_ID",
    COUNT(DISTINCT "USER_ID")                         AS "UNIQUE_USERS_SESSION_START"
FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC."USERS_BEHAVIORS_APP_SESSIONSTART_VIEW"
WHERE CAST(TO_TIMESTAMP_NTZ("TIME") AS DATE) BETWEEN '2023-06-01' AND '2023-06-07'
GROUP BY
    CAST(TO_TIMESTAMP_NTZ("TIME") AS DATE),
    "APP_GROUP_ID"
ORDER BY
    "SESSION_START_DATE" ASC,
    "APP_GROUP_ID" ASC;