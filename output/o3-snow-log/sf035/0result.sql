SELECT
    "APP_GROUP_ID",
    TO_DATE(TO_TIMESTAMP_NTZ("TIME"))              AS "START_DAY",
    COUNT(DISTINCT "USER_ID")                      AS "UNIQUE_USERS"
FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC."USERS_BEHAVIORS_APP_SESSIONSTART_VIEW"
WHERE TO_DATE(TO_TIMESTAMP_NTZ("TIME")) BETWEEN '2023-06-01' AND '2023-06-07'
GROUP BY
    "APP_GROUP_ID",
    TO_DATE(TO_TIMESTAMP_NTZ("TIME"))
ORDER BY
    "START_DAY",
    "APP_GROUP_ID";