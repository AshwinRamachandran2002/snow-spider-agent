WITH session_data AS (
    SELECT
        "APP_GROUP_ID",
        CAST(TO_TIMESTAMP("TIME") AS DATE) AS "SESSION_DAY",
        "USER_ID"
    FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC."USERS_BEHAVIORS_APP_SESSIONSTART_VIEW"
    WHERE CAST(TO_TIMESTAMP("TIME") AS DATE) BETWEEN '2023-06-01' AND '2023-06-07'
)

SELECT
    "APP_GROUP_ID",
    "SESSION_DAY",
    COUNT(DISTINCT "USER_ID") AS "UNIQUE_USERS_STARTED_SESSION"
FROM session_data
GROUP BY
    "APP_GROUP_ID",
    "SESSION_DAY"
ORDER BY
    "SESSION_DAY" ASC,
    "APP_GROUP_ID" ASC;