SELECT
    "APP_GROUP_ID",
    CAST(DATE_TRUNC('day', TO_TIMESTAMP_LTZ("TIME")) AS DATE) AS "SESSION_START_DAY",
    COUNT(DISTINCT "USER_ID")                                AS "UNIQUE_USERS_STARTED_SESSION"
FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC.USERS_BEHAVIORS_APP_SESSIONSTART_VIEW
WHERE CAST(TO_TIMESTAMP_LTZ("TIME") AS DATE) BETWEEN '2023-06-01' AND '2023-06-07'
GROUP BY
    "APP_GROUP_ID",
    CAST(DATE_TRUNC('day', TO_TIMESTAMP_LTZ("TIME")) AS DATE)
ORDER BY
    "SESSION_START_DAY" ASC,
    "APP_GROUP_ID"       ASC;