SELECT
    "APP_GROUP_ID",
    DATE_TRUNC('DAY', COALESCE(TO_TIMESTAMP_NTZ("TIME"), "SF_CREATED_AT"))     AS "START_DAY",
    COUNT(DISTINCT "USER_ID")                                                  AS "UNIQUE_USERS"
FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC."USERS_BEHAVIORS_APP_SESSIONSTART_VIEW"
WHERE
      COALESCE(TO_TIMESTAMP_NTZ("TIME"), "SF_CREATED_AT") >= DATE '2023-06-01'
  AND COALESCE(TO_TIMESTAMP_NTZ("TIME"), "SF_CREATED_AT") <  DATE '2023-06-08'
GROUP BY
    "APP_GROUP_ID",
    DATE_TRUNC('DAY', COALESCE(TO_TIMESTAMP_NTZ("TIME"), "SF_CREATED_AT"))
ORDER BY
    "APP_GROUP_ID",
    "START_DAY";