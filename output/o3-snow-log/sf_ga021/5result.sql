    UNION ALL SELECT "event_date","event_name","user_pseudo_id" FROM FIREBASE.ANALYTICS_153293282."EVENTS_20180714"
    UNION ALL SELECT "event_date","event_name","user_pseudo_id" FROM FIREBASE.ANALYTICS_153293282."EVENTS_20180715"
    UNION ALL SELECT "event_date","event_name","user_pseudo_id" FROM FIREBASE.ANALYTICS_153293282."EVENTS_20180716"
