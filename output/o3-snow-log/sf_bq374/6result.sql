SESSIONS AS
(
    SELECT
        "fullVisitorId"                          AS full_visitor_id,
        "visitStartTime"::NUMBER                AS visit_start,
        PARSE_JSON("totals")                    AS totals_j,
        "date"                                  AS yyyymmdd
    FROM ALL_SESSIONS
    /* keep only the required period */
    WHERE "date" BETWEEN '20160801' AND '20170430'
),
FIRST_VISIT AS
(
    SELECT
        full_visitor_id,
        MIN(visit_start) AS first_visit_start
    FROM SESSIONS
    WHERE totals_j:"newVisits"::NUMBER = 1
    GROUP BY full_visitor_id
),
INITIAL_SESSIONS AS
(
    /* new-user first sessions lasting >5 min */
    SELECT s.*
    FROM   SESSIONS s
    JOIN   FIRST_VISIT f
           ON f.full_visitor_id = s.full_visitor_id
          AND f.first_visit_start = s.visit_start
    WHERE  s.totals_j:"timeOnSite"::NUMBER > 300           /* >5 minutes */
),
PURCHASE_AFTER AS
(
    /* any later session (same period) with a transaction */
    SELECT DISTINCT s.full_visitor_id
    FROM   SESSIONS s
    JOIN   INITIAL_SESSIONS i
           ON i.full_visitor_id = s.full_visitor_id
          AND s.visit_start       > i.visit_start          /* later visit  */
    WHERE  COALESCE( s.totals_j:"transactions"::NUMBER , 
                     (s.totals_j:"totalTransactionRevenue"::NUMBER) , 0 ) > 0
)
/* ---------------------------  FINAL RESULT  ----------------------- */
SELECT
    COUNT(DISTINCT p.full_visitor_id)                                            AS purchasers_after_first_visit,
    COUNT(DISTINCT i.full_visitor_id)                                            AS total_new_users,
    ROUND(
        100.0 * COUNT(DISTINCT p.full_visitor_id) 
              / NULLIF(COUNT(DISTINCT i.full_visitor_id),0)
        , 4)                                                                     AS pct_new_users_with_long_first_visit_then_purchase
FROM INITIAL_SESSIONS i
LEFT JOIN PURCHASE_AFTER p
       ON p.full_visitor_id = i.full_visitor_id;