/* ------------------------------------------------------------------------- */
/*  Keep only sessions with pageviews and pull the elements we need          */
/* ------------------------------------------------------------------------- */
filtered AS (
    SELECT
        TO_CHAR(TO_DATE("date",'YYYYMMDD'),'YYYY-MM') AS month,
        "fullVisitorId"                              AS visitor_id,
        TRY_TO_NUMBER(("totals":"pageviews")::string) AS pageviews,
        COALESCE(
            TRY_TO_NUMBER(("totals":"transactions")::string),
            TRY_TO_NUMBER(("totals":"totalTransactions")::string),
            TRY_TO_NUMBER(("totals":"totalTransactionRevenue")::string)
        )                                             AS purchase_signal
    FROM union_sessions
    WHERE TRY_TO_NUMBER(("totals":"pageviews")::string) IS NOT NULL
),

/* ------------------------------------------------------------------------- */
/*  Classify each session                                                    */
/* ------------------------------------------------------------------------- */
classified AS (
    SELECT
        month,
        visitor_id,
        pageviews,
        CASE WHEN purchase_signal > 0 THEN 'purchase' ELSE 'non_purchase' END AS classification
    FROM filtered
),

/* ------------------------------------------------------------------------- */
/*  Aggregate pageviews per visitor / month / class                          */
/* ------------------------------------------------------------------------- */
visitor_monthly AS (
    SELECT
        month,
        visitor_id,
        classification,
        SUM(pageviews) AS total_pageviews
    FROM classified
    GROUP BY month, visitor_id, classification
)

/* ------------------------------------------------------------------------- */
/*  Final result – average per-visitor pageviews, side-by-side               */
/* ------------------------------------------------------------------------- */
SELECT
    month,
    AVG(CASE WHEN classification = 'purchase'     THEN total_pageviews END) AS purchase_avg_pageviews,
    AVG(CASE WHEN classification = 'non_purchase' THEN total_pageviews END) AS non_purchase_avg_pageviews
FROM visitor_monthly
GROUP BY month
ORDER BY month;