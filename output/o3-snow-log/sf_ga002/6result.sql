flattened AS (  /* 2. explode the ITEMS array */
    SELECT
        TO_CHAR(TO_DATE("EVENT_DATE",'YYYYMMDD'),'YYYY-MM') AS "MONTH",
        "USER_PSEUDO_ID"                                    AS "USER_ID",
        itm.value:"item_name"::string                       AS "ITEM_NAME",
        COALESCE(itm.value:"quantity"::number,1)            AS "QUANTITY"
    FROM raw,
         LATERAL FLATTEN(input => raw."ITEMS") itm
    WHERE itm.value:"item_name" IS NOT NULL
),
target_buyers AS ( /* 3. buyers of the Google Red Speckled Tee, per month */ 
    SELECT DISTINCT "MONTH", "USER_ID"
    FROM   flattened
    WHERE  "ITEM_NAME" = 'Google Red Speckled Tee'
),
other_purchases AS ( /* 4. other items those buyers purchased, summed */ 
    SELECT
        f."MONTH",
        f."ITEM_NAME",
        SUM(f."QUANTITY") AS "TOTAL_QTY"
    FROM   flattened f
    JOIN   target_buyers tb
           ON f."MONTH"   = tb."MONTH"
          AND f."USER_ID" = tb."USER_ID"
    WHERE  f."ITEM_NAME" <> 'Google Red Speckled Tee'
    GROUP  BY f."MONTH", f."ITEM_NAME"
),
ranked AS (      /* 5. rank items by quantity within each month           */ 
    SELECT
        "MONTH",
        "ITEM_NAME",
        "TOTAL_QTY",
        RANK() OVER (PARTITION BY "MONTH" ORDER BY "TOTAL_QTY" DESC) AS rnk
    FROM   other_purchases
)
SELECT
    "MONTH",
    "ITEM_NAME"   AS "MOST_PURCHASED_OTHER_PRODUCT",
    "TOTAL_QTY"   AS "QUANTITY"
FROM   ranked
WHERE  rnk = 1                     /* take the top-purchased item(s)     */
