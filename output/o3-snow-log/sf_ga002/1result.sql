MONTHS_FILTERED AS (      -- 2. keep only the three months in question
    SELECT *
    FROM ALL_EVENTS
    WHERE TO_CHAR(TO_DATE("EVENT_DATE",'YYYYMMDD'), 'YYYY-MM')
          IN ('2020-11','2020-12','2021-01')
),

TEE_BUYERS AS (           -- 3. users who bought the Google Red Speckled Tee
    SELECT DISTINCT
           "USER_PSEUDO_ID"                                                      AS buyer_id,
           TO_CHAR(TO_DATE("EVENT_DATE",'YYYYMMDD'),'YYYY-MM')                   AS month
    FROM MONTHS_FILTERED,
         LATERAL FLATTEN(INPUT => "ITEMS") AS itm
    WHERE "EVENT_NAME" = 'purchase'
      AND itm.value:"item_name"::STRING = 'Google Red Speckled Tee'
),

OTHER_PURCHASES AS (      -- 4. every OTHER product purchased by those users
    SELECT
        TO_CHAR(TO_DATE(mf."EVENT_DATE",'YYYYMMDD'),'YYYY-MM')                   AS month,
        itm.value:"item_name"::STRING                                            AS product_name,
        itm.value:"quantity"::NUMBER                                             AS qty
    FROM MONTHS_FILTERED    mf
    INNER JOIN TEE_BUYERS   tb
            ON  tb.buyer_id = mf."USER_PSEUDO_ID"
            AND tb.month    = TO_CHAR(TO_DATE(mf."EVENT_DATE",'YYYYMMDD'),'YYYY-MM')
    ,   LATERAL FLATTEN(INPUT => mf."ITEMS") AS itm
    WHERE mf."EVENT_NAME" = 'purchase'
      AND itm.value:"item_name"::STRING IS NOT NULL
      AND itm.value:"item_name"::STRING <> 'Google Red Speckled Tee'
)

-- 5. final aggregation
SELECT
    month,
    product_name          AS other_product,
    SUM(qty)              AS total_quantity
FROM OTHER_PURCHASES
GROUP BY month, product_name
ORDER BY month,
         total_quantity DESC NULLS LAST;