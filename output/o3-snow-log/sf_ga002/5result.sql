/*----------------------------------------------------------------
   2.  Keep only purchase lines; explode the ITEMS array
----------------------------------------------------------------*/
PURCHASE_LINES AS (
    SELECT
        DATE_TRUNC('MONTH', TO_DATE("EVENT_DATE",'YYYYMMDD'))                          AS MONTH_START,
        "USER_PSEUDO_ID"                                                              AS USER_ID,
        itm.value:"item_name"::string                                                 AS ITEM_NAME,
        itm.value:"quantity"::number                                                  AS QTY
    FROM ALL_EVENTS
         ,LATERAL FLATTEN(INPUT => "ITEMS") AS itm
    WHERE "EVENT_NAME" = 'purchase'
          AND itm.value:"item_name" IS NOT NULL
),

/*----------------------------------------------------------------
   3.  Identify every user who bought the Google Red Speckled Tee
----------------------------------------------------------------*/
TEE_USERS AS (
    SELECT DISTINCT USER_ID
    FROM PURCHASE_LINES
    WHERE ITEM_NAME = 'Google Red Speckled Tee'
),

/*----------------------------------------------------------------
   4.  Aggregate other products bought by those users
----------------------------------------------------------------*/
OTHER_PRODUCT_COUNTS AS (
    SELECT
        MONTH_START,
        ITEM_NAME,
        SUM(QTY) AS TOTAL_QTY
    FROM PURCHASE_LINES
    WHERE USER_ID IN (SELECT USER_ID FROM TEE_USERS)
      AND ITEM_NAME <> 'Google Red Speckled Tee'
    GROUP BY MONTH_START, ITEM_NAME
),

/*----------------------------------------------------------------
   5.  Pick the most-purchased other product for each month
----------------------------------------------------------------*/
RANKED AS (
    SELECT
        MONTH_START,
        ITEM_NAME,
        TOTAL_QTY,
        ROW_NUMBER() OVER (PARTITION BY MONTH_START
                           ORDER BY TOTAL_QTY DESC NULLS LAST) AS RN
    FROM OTHER_PRODUCT_COUNTS
)

SELECT
    TO_CHAR(MONTH_START,'YYYY-MM') AS MONTH,
    ITEM_NAME                     AS MOST_PURCHASED_PRODUCT,
    TOTAL_QTY                     AS QUANTITY
FROM RANKED
WHERE RN = 1
ORDER BY MONTH_START;