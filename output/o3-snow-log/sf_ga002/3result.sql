purchase_events AS (
    SELECT *
    FROM union_events
    WHERE  "EVENT_NAME" = 'purchase'
       AND ITEMS IS NOT NULL
),

/* explode ITEMS JSON into individual product rows */
purchase_items AS (
    SELECT  TO_CHAR(DATE_TRUNC('month', TO_DATE("EVENT_DATE",'YYYYMMDD')), 'YYYY-MM') AS month,
            "USER_PSEUDO_ID"                                                          AS user_id,
            itm.value:"item_name"::STRING                                             AS product_name,
            COALESCE(itm.value:"quantity"::NUMBER, 1)                                 AS quantity
    FROM   purchase_events,
           LATERAL FLATTEN( INPUT => PARSE_JSON( ITEMS ) ) itm
),

tee_buyers AS (   /* users who bought the Tee in each month */
    SELECT DISTINCT month, user_id
    FROM   purchase_items
    WHERE  product_name = 'Google Red Speckled Tee'
),

other_products AS (  /* products (excluding Tee) bought by those users */
    SELECT  pi.month,
            pi.product_name,
            SUM(pi.quantity) AS total_quantity
    FROM    purchase_items pi
            JOIN tee_buyers tb
              ON pi.month = tb.month
             AND pi.user_id = tb.user_id
    WHERE   pi.product_name <> 'Google Red Speckled Tee'
    GROUP BY pi.month, pi.product_name
)

SELECT  month,
        product_name,
        total_quantity
FROM    other_products
ORDER BY month,
         total_quantity DESC NULLS LAST;