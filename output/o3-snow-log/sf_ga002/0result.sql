/* ----------  All purchase-level line items ---------- */
purchase_items AS (
    SELECT
        TO_DATE("EVENT_DATE",'YYYYMMDD')                                         AS event_dt,
        DATE_TRUNC('month', TO_DATE("EVENT_DATE",'YYYYMMDD'))                    AS event_month,
        "USER_PSEUDO_ID"                                                         AS user_id,
        itm.value:"item_name"::string                                            AS item_name,
        COALESCE(itm.value:"quantity"::number , 1)                               AS quantity
    FROM all_events   e,
         LATERAL FLATTEN (INPUT => e."ITEMS")              itm
    WHERE e."EVENT_NAME" = 'purchase'
),

/* ----------  Identify every shopper who bought the Google Red Speckled Tee ---------- */
tee_buyers AS (
    SELECT DISTINCT user_id
    FROM   purchase_items
    WHERE  item_name = 'Google Red Speckled Tee'
),

/* ----------  Aggregate other products those same shoppers bought ---------- */
other_purchases AS (
    SELECT
        event_month,
        item_name,
        SUM(quantity)  AS total_quantity
    FROM   purchase_items
    WHERE  user_id IN (SELECT user_id FROM tee_buyers)
      AND  item_name <> 'Google Red Speckled Tee'
    GROUP  BY event_month, item_name
)

SELECT
    TO_CHAR(event_month,'YYYY-MM')  AS month,
    item_name,
    total_quantity
FROM   other_purchases
ORDER  BY event_month,
          total_quantity DESC NULLS LAST;