all_events AS (
    SELECT
        user_pseudo_id,
        PARSE_DATE('%Y%m%d', event_date) AS event_dt
    FROM unioned
    WHERE event_name = 'session_start'
),
first_visit AS (
    SELECT
        user_pseudo_id,
        MIN(event_dt) AS first_date
    FROM all_events
    GROUP BY user_pseudo_id
    HAVING first_date >= DATE '2018-07-02'
),
wk4_return AS (
    SELECT DISTINCT ae.user_pseudo_id
    FROM first_visit fv
    JOIN all_events ae
      ON ae.user_pseudo_id = fv.user_pseudo_id
    WHERE DATE_DIFF(ae.event_dt, fv.first_date, DAY) BETWEEN 22 AND 28
),
cohort_stats AS (
    SELECT
        DATE_TRUNC(first_date, WEEK(MONDAY)) AS cohort_week,
        COUNT(*) AS cohort_users,
        COUNTIF(user_pseudo_id IN (SELECT user_pseudo_id FROM wk4_return)) AS wk4_users,
        SAFE_DIVIDE(COUNTIF(user_pseudo_id IN (SELECT user_pseudo_id FROM wk4_return)), COUNT(*)) AS wk4_retention
    FROM first_visit
    GROUP BY cohort_week
)
SELECT
    FORMAT_DATE('%Y-%m-%d', cohort_week) AS cohort_start_date
FROM cohort_stats
ORDER BY wk4_retention DESC, cohort_week
