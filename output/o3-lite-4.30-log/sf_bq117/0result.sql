WITH last15 AS (
    SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2009"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2010"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2011"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2012"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2013"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2014"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2015"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2016"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2017"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2018"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2019"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2020"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2021"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2022"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2023"
    UNION ALL SELECT * FROM NOAA_DATA.NOAA_HISTORIC_SEVERE_STORMS."STORMS_2024"
),
dedup AS (
    SELECT *,
           ROW_NUMBER() OVER (PARTITION BY "event_id" ORDER BY "damage_property" DESC NULLS LAST) AS rn
    FROM   last15
),
unique_events AS (
    SELECT *
    FROM   dedup
    WHERE  rn = 1
),
top100 AS (
    SELECT *
    FROM   unique_events
    ORDER  BY "damage_property" DESC NULLS LAST
    LIMIT  100
),
month_counts AS (
    SELECT MONTH(TO_TIMESTAMP_LTZ("event_begin_time" / 1e6)) AS most_affected_month,
           COUNT(*)                                          AS total_severe_storm_events
    FROM   top100
    GROUP  BY most_affected_month
)
SELECT most_affected_month,
       total_severe_storm_events
FROM   month_counts
ORDER  BY total_severe_storm_events DESC, most_affected_month
LIMIT  1;