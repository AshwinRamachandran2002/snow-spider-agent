WITH fl_largest_zip AS (
    SELECT
        SUBSTR(c."GEO_ID", 5) AS "ZIP_CODE"
    FROM US_ADDRESSES__POI.CYBERSYN.GEOGRAPHY_CHARACTERISTICS c
    JOIN US_ADDRESSES__POI.CYBERSYN.GEOGRAPHY_RELATIONSHIPS  r
          ON c."GEO_ID" = r."GEO_ID"
    WHERE r."RELATED_GEO_ID"    = 'geoId/12'            -- Florida
      AND c."RELATIONSHIP_TYPE" = 'coordinates_wkt'
      AND c."GEO_ID" LIKE 'zip/%'
    ORDER BY ST_AREA(ST_GEOGFROMTEXT(c."VALUE")) DESC
    LIMIT 1
)

SELECT
    a."NUMBER"       AS "ADDRESS_NUMBER",
    a."STREET"       AS "STREET_NAME",
    a."STREET_TYPE"  AS "STREET_TYPE"
FROM US_ADDRESSES__POI.CYBERSYN.US_ADDRESSES a
JOIN fl_largest_zip z
  ON a."ZIP" = z."ZIP_CODE"
WHERE a."STATE" = 'FL'
ORDER BY a."LATITUDE" DESC NULLS LAST, a."ADDRESS_ID"
LIMIT 10;