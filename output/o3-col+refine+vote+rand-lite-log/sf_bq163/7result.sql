SELECT
  "FEATURE_NAME",
  AVG(CASE WHEN "SEX" = 'female' THEN "X_VALUE" END)                         AS "AVG_FEMALE",
  AVG(CASE WHEN "SEX" = 'male'   THEN "X_VALUE" END)                         AS "AVG_MALE",
  AVG(CASE WHEN "SEX" = 'female' THEN "X_VALUE" END)
    - AVG(CASE WHEN "SEX" = 'male' THEN "X_VALUE" END)                       AS "FEMALE_MINUS_MALE"
FROM HTAN_2.HTAN."SCRNASEQ_MSK_SCLC_COMBINED_SAMPLES_CURRENT"
WHERE "CLUSTERS" = '41'
  AND "CELL_TYPE" ILIKE '%epithelial%'
  AND "DEVELOPMENT_STAGE" ILIKE '%74-year-old%'
GROUP BY "FEATURE_NAME"
ORDER BY ABS("FEMALE_MINUS_MALE") DESC NULLS LAST
LIMIT 20;