WITH female AS (
    SELECT
        "FEATURE_NAME",
        AVG("X_VALUE") AS "AVG_F"
    FROM HTAN_2.HTAN."SCRNASEQ_MSK_SCLC_COMBINED_SAMPLES_CURRENT"
    WHERE "CLUSTERS" = '41'
      AND "CELL_TYPE" ILIKE '%epithelial%'
      AND "DEVELOPMENT_STAGE" ILIKE '74-year-old%'
      AND "SEX" = 'female'
    GROUP BY "FEATURE_NAME"
),
male AS (
    SELECT
        "FEATURE_NAME",
        AVG("X_VALUE") AS "AVG_M"
    FROM HTAN_2.HTAN."SCRNASEQ_MSK_SCLC_COMBINED_SAMPLES_CURRENT"
    WHERE "CLUSTERS" = '41'
      AND "CELL_TYPE" ILIKE '%epithelial%'
      AND "DEVELOPMENT_STAGE" ILIKE '74-year-old%'
      AND "SEX" = 'male'
    GROUP BY "FEATURE_NAME"
)
SELECT
    f."FEATURE_NAME",
    (f."AVG_F" - m."AVG_M") AS "FEMALE_MINUS_MALE_DIFF",
    f."AVG_F" AS "AVG_FEMALE_X",
    m."AVG_M" AS "AVG_MALE_X"
FROM female f
JOIN male   m USING ("FEATURE_NAME")
ORDER BY "FEMALE_MINUS_MALE_DIFF" DESC NULLS LAST
LIMIT 20;