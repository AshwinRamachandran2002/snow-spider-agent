WITH AMS AS (
    SELECT
        "CLASS",
        "SUBCLASS",
        SUM(TO_NUMBER("SURFACE_AREA_SQ_M")) AS "TOTAL_SURFACE_AMS",
        COUNT(*)                           AS "TOTAL_COUNT_AMS"
    FROM
        NETHERLANDS_OPEN_MAP_DATA.NETHERLANDS."V_BUILDING"
    WHERE
        "CONTAINS_ADDRESSES" ILIKE '%Amsterdam%'
    GROUP BY
        "CLASS",
        "SUBCLASS"
),
ROT AS (
    SELECT
        "CLASS",
        "SUBCLASS",
        SUM(TO_NUMBER("SURFACE_AREA_SQ_M")) AS "TOTAL_SURFACE_ROT",
        COUNT(*)                           AS "TOTAL_COUNT_ROT"
    FROM
        NETHERLANDS_OPEN_MAP_DATA.NETHERLANDS."V_BUILDING"
    WHERE
        "CONTAINS_ADDRESSES" ILIKE '%Rotterdam%'
    GROUP BY
        "CLASS",
        "SUBCLASS"
)
SELECT
    COALESCE(AMS."CLASS", ROT."CLASS")         AS "CLASS",
    COALESCE(AMS."SUBCLASS", ROT."SUBCLASS")   AS "SUBCLASS",
    AMS."TOTAL_SURFACE_AMS",
    AMS."TOTAL_COUNT_AMS",
    ROT."TOTAL_SURFACE_ROT",
    ROT."TOTAL_COUNT_ROT"
FROM
    AMS
FULL OUTER JOIN
    ROT
ON  AMS."CLASS"    = ROT."CLASS"
AND AMS."SUBCLASS" = ROT."SUBCLASS"
ORDER BY
    "CLASS",
    "SUBCLASS";