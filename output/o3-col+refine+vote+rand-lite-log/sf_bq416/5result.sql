SELECT
    "BLOCK_NUMBER",
    PARSE_JSON("ARGS")[0]::STRING AS "FROM_ADDRESS_HEX",
    PARSE_JSON("ARGS")[1]::STRING AS "TO_ADDRESS_HEX",
    TRY_TO_NUMBER(PARSE_JSON("ARGS")[2]::STRING) / 1000000 AS "USDT_AMOUNT"
FROM "GOOG_BLOCKCHAIN"."GOOG_BLOCKCHAIN_ARBITRUM_ONE_US"."DECODED_EVENTS"
WHERE "EVENT_HASH" = '0xddf252ad1be2c89b69c2b068fc378daa952ba7f163c4a11628f55a4df523b3ef'
  AND LOWER("ADDRESS") = '0xfd086bc7cd5c481dcc9c85ebe478a1c0b69fcbb9'   -- USDT on Arbitrum
ORDER BY "USDT_AMOUNT" DESC NULLS LAST
LIMIT 3;