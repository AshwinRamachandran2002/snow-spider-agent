SELECT
    EXTRACT(year FROM "DATE_OF_LOSS")                                AS "YEAR",
    SUM(COALESCE("BUILDING_DAMAGE_AMOUNT",  0))                      AS "TOTAL_BUILDING_DAMAGE_USD",
    SUM(COALESCE("CONTENTS_DAMAGE_AMOUNT", 0))                       AS "TOTAL_CONTENTS_DAMAGE_USD"
FROM WEATHER__ENVIRONMENT.CYBERSYN.FEMA_NATIONAL_FLOOD_INSURANCE_PROGRAM_CLAIM_INDEX
WHERE "NFIP_COMMUNITY_NAME" = 'City Of New York'
  AND EXTRACT(year FROM "DATE_OF_LOSS") BETWEEN 2010 AND 2019
GROUP BY "YEAR"
ORDER BY "YEAR";