-- Unique users who started sessions each day (per app group)
-- between 2023-06-01 and 2023-06-07, using the epoch-seconds “TIME” column
SELECT
  CAST(TO_TIMESTAMP_LTZ("TIME") AS DATE) AS "SESSION_START_DATE",
  "APP_GROUP_ID",
  COUNT(DISTINCT "USER_ID")          AS "UNIQUE_USERS"
FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC."USERS_BEHAVIORS_APP_SESSIONSTART_VIEW"
WHERE CAST(TO_TIMESTAMP_LTZ("TIME") AS DATE) BETWEEN '2023-06-01' AND '2023-06-07'
GROUP BY
  CAST(TO_TIMESTAMP_LTZ("TIME") AS DATE),
  "APP_GROUP_ID"
ORDER BY
  "SESSION_START_DATE",
  "APP_GROUP_ID";