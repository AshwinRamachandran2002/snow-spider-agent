SELECT
  "APP_GROUP_ID",
  TO_DATE(TO_TIMESTAMP_LTZ("TIME")) AS "session_day",
  COUNT(DISTINCT "USER_ID")        AS "unique_users_started_sessions"
FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC."USERS_BEHAVIORS_APP_SESSIONSTART_VIEW"
WHERE "TIME" >= 1685577600            -- 2023-06-01 00:00:00 UTC
  AND "TIME" <  1686182400            -- 2023-06-08 00:00:00 UTC (exclusive)
GROUP BY
  "APP_GROUP_ID",
  TO_DATE(TO_TIMESTAMP_LTZ("TIME"))
ORDER BY
  "APP_GROUP_ID",
  "session_day";