SELECT
    "CLASS",
    "SUBCLASS",
    ROUND( SUM( CASE WHEN "QUADKEY" ILIKE '12020210%' 
                     THEN TRY_TO_DOUBLE("LENGTH_M") 
                END ), 4) AS "AMSTERDAM_TOTAL_M",
    ROUND( SUM( CASE WHEN "QUADKEY" ILIKE '12020211%' 
                     THEN TRY_TO_DOUBLE("LENGTH_M") 
                END ), 4) AS "ROTTERDAM_TOTAL_M"
FROM NETHERLANDS_OPEN_MAP_DATA.NETHERLANDS."V_ROAD"
WHERE "QUADKEY" ILIKE '12020210%' 
   OR "QUADKEY" ILIKE '12020211%'
GROUP BY "CLASS", "SUBCLASS"
ORDER BY "CLASS", "SUBCLASS";