/*  Top-5 U.S. ZIP codes with the greatest number of hail-storm events
    recorded in Storm-Data during the most recent ten seasons (2015-2024).
*/
SELECT
       z."zip_code",
       COUNT(*) AS "hail_events_10yr"
FROM  (      SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2015"
       UNION ALL SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2016"
       UNION ALL SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2017"
       UNION ALL SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2018"
       UNION ALL SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2019"
       UNION ALL SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2020"
       UNION ALL SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2021"
       UNION ALL SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2022"
       UNION ALL SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2023"
       UNION ALL SELECT * FROM "NOAA_DATA_PLUS"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2024"
     )  s
JOIN  "NOAA_DATA_PLUS"."GEO_US_BOUNDARIES"."ZIP_CODES"  z
      ON  UPPER(z."county") ILIKE '%' || UPPER(s."cz_name") || '%'
WHERE s."event_type" ILIKE '%hail%'
GROUP BY z."zip_code"
ORDER BY "hail_events_10yr" DESC NULLS LAST
LIMIT 5;