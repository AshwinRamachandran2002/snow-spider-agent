SELECT
    "DATE",
    SUM("VALUE") AS "CUMULATIVE_NEAR_DEFAULT_RATIO"
FROM "US_REAL_ESTATE"."CYBERSYN"."FHFA_MORTGAGE_PERFORMANCE_TIMESERIES"
WHERE "GEO_ID" = 'geoId/06'     -- California
  AND (
       "VARIABLE_NAME" ILIKE '%90 to 180 Days Past Due Date%'
    OR "VARIABLE_NAME" ILIKE '%in Forbearance%'
    OR "VARIABLE_NAME" ILIKE '%Foreclosure%'
    OR "VARIABLE_NAME" ILIKE '%Bankruptcy%'
    OR "VARIABLE_NAME" ILIKE '%Deed%Lieu%'
      )
  AND "DATE" BETWEEN '2023-01-01' AND '2023-12-31'
GROUP BY "DATE"
ORDER BY "DATE";