WITH all_events AS (          -- gather the past 15 years of storm records (2010-2024)
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2010" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2011" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2012" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2013" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2014" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2015" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2016" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2017" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2018" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2019" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2020" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2021" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2022" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2023" UNION ALL
    SELECT * FROM "NOAA_DATA"."NOAA_HISTORIC_SEVERE_STORMS"."STORMS_2024"
), ranked AS (                -- rank events by property damage (largest first)
    SELECT
        TO_CHAR(TO_TIMESTAMP_LTZ("event_begin_time" / 1000000), 'MM') AS "month",
        ROW_NUMBER() OVER (ORDER BY "damage_property" DESC NULLS LAST) AS "rnk"
    FROM all_events
), top100 AS (                -- retain the 100 costliest events
    SELECT "month"
    FROM ranked
    WHERE "rnk" <= 100
), month_counts AS (          -- count how many of those fall in each month
    SELECT "month", COUNT(*) AS "cnt"
    FROM top100
    GROUP BY "month"
)
SELECT MAX("cnt") AS "most_affected_month_event_count"
FROM month_counts;