SELECT
    "APP_GROUP_ID",
    TO_TIMESTAMP("TIME")::DATE                    AS "SESSION_START_DAY",
    COUNT(DISTINCT "USER_ID")                     AS "UNIQUE_USERS_STARTED_SESSIONS"
FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC."USERS_BEHAVIORS_APP_SESSIONSTART_VIEW"
WHERE "TIME" >= DATE_PART(EPOCH_SECOND, TO_TIMESTAMP_NTZ('2023-06-01 00:00:00'))
  AND "TIME" <  DATE_PART(EPOCH_SECOND, TO_TIMESTAMP_NTZ('2023-06-08 00:00:00'))
GROUP BY
    "APP_GROUP_ID",
    "SESSION_START_DAY"
ORDER BY
    "APP_GROUP_ID",
    "SESSION_START_DAY";