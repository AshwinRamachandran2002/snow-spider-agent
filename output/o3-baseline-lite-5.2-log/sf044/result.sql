WITH m7 AS (
    SELECT 'AAPL'  AS "TICKER" UNION ALL
    SELECT 'MSFT'  UNION ALL
    SELECT 'AMZN'  UNION ALL
    SELECT 'GOOGL' UNION ALL
    SELECT 'NVDA'  UNION ALL
    SELECT 'META'  UNION ALL
    SELECT 'TSLA'
),
price_window AS (
    SELECT 
        s."TICKER",
        s."DATE",
        s."VALUE"
    FROM FINANCE__ECONOMICS.CYBERSYN."STOCK_PRICE_TIMESERIES" s
    JOIN m7        ON s."TICKER" = m7."TICKER"
    WHERE s."VARIABLE" = 'post-market_close'
      AND s."DATE" BETWEEN '2024-01-01' AND '2024-06-30'
),
first_last AS (
    SELECT
        "TICKER",
        MIN_BY("VALUE", "DATE") AS "VALUE_START",
        MAX_BY("VALUE", "DATE") AS "VALUE_END"
    FROM price_window
    GROUP BY "TICKER"
)
SELECT
    "TICKER",
    ROUND((( "VALUE_END" - "VALUE_START") / "VALUE_START") * 100, 4) AS "PCT_CHANGE_JAN1_TO_JUN30_2024"
FROM first_last
ORDER BY "TICKER";