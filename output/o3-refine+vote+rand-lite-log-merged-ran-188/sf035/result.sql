SELECT
  "APP_GROUP_ID",
  TO_DATE(TO_TIMESTAMP("TIME")) AS "SESSION_START_DAY",
  COUNT(DISTINCT "USER_ID") AS "UNIQUE_USERS_STARTED_SESSION"
FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC."USERS_BEHAVIORS_APP_SESSIONSTART_VIEW"
WHERE "TIME" BETWEEN 1685577600 AND 1686182399   -- 2023-06-01 00:00:00 UTC through 2023-06-07 23:59:59 UTC
GROUP BY
  "APP_GROUP_ID",
  TO_DATE(TO_TIMESTAMP("TIME"))
ORDER BY
  "SESSION_START_DAY",
  "APP_GROUP_ID";