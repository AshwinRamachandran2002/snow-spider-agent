WITH "FL_ADDRESSES" AS (
    SELECT
        "ADDRESS_ID",
        "NUMBER",
        "STREET",
        "STREET_TYPE",
        "LATITUDE",
        "ZIP"
    FROM US_ADDRESSES__POI.CYBERSYN.US_ADDRESSES
    WHERE "STATE" = 'FL'
      AND "LATITUDE" IS NOT NULL
      AND "ZIP" IS NOT NULL
), 
"ZIP_COUNTS" AS (
    SELECT
        "ZIP",
        COUNT(*) AS "CNT"
    FROM "FL_ADDRESSES"
    GROUP BY "ZIP"
), 
"LARGEST_ZIP" AS (
    SELECT
        "ZIP"
    FROM "ZIP_COUNTS"
    ORDER BY "CNT" DESC, "ZIP"
    LIMIT 1
), 
"TARGET_ADDRESSES" AS (
    SELECT
        f."NUMBER",
        f."STREET",
        f."STREET_TYPE",
        f."LATITUDE"
    FROM "FL_ADDRESSES" f
    JOIN "LARGEST_ZIP" l
      ON f."ZIP" = l."ZIP"
)
SELECT
    "NUMBER"          AS "ADDRESS_NUMBER",
    "STREET"          AS "STREET_NAME",
    "STREET_TYPE"
FROM "TARGET_ADDRESSES"
ORDER BY
    "LATITUDE" DESC NULLS LAST,
    "NUMBER"
LIMIT 10;