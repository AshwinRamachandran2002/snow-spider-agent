WITH "FILTERED_USERS" AS (
    SELECT 
        "id",
        "age"
    FROM THELOOK_ECOMMERCE.THELOOK_ECOMMERCE."USERS"
    WHERE TO_TIMESTAMP("created_at" / 1000000) BETWEEN '2019-01-01' AND '2022-04-30 23:59:59'
),
"AGE_STATS" AS (
    SELECT 
        MAX("age") AS "MAX_AGE",
        MIN("age") AS "MIN_AGE"
    FROM "FILTERED_USERS"
),
"AGE_COUNTS" AS (
    SELECT
        SUM(CASE WHEN "age" = (SELECT "MAX_AGE" FROM "AGE_STATS") THEN 1 ELSE 0 END) AS "OLDEST_USERS",
        SUM(CASE WHEN "age" = (SELECT "MIN_AGE" FROM "AGE_STATS") THEN 1 ELSE 0 END) AS "YOUNGEST_USERS"
    FROM "FILTERED_USERS"
)
SELECT 
    "OLDEST_USERS" - "YOUNGEST_USERS" AS "DIFFERENCE_IN_USER_COUNT"
FROM "AGE_COUNTS";