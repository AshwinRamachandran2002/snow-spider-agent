-- Building classification comparison: Amsterdam vs. Rotterdam
WITH amsterdam AS (
    SELECT
        "CLASS",
        "SUBCLASS",
        COUNT(*)                                AS "AMSTERDAM_BUILDING_COUNT",
        SUM(TRY_TO_DOUBLE("SURFACE_AREA_SQ_M")) AS "AMSTERDAM_TOTAL_SURFACE_SQ_M"
    FROM NETHERLANDS_OPEN_MAP_DATA.NETHERLANDS."V_BUILDING"
    WHERE "CONTAINS_ADDRESSES" ILIKE '%Amsterdam%'
    GROUP BY "CLASS", "SUBCLASS"
),
rotterdam AS (
    SELECT
        "CLASS",
        "SUBCLASS",
        COUNT(*)                                AS "ROTTERDAM_BUILDING_COUNT",
        SUM(TRY_TO_DOUBLE("SURFACE_AREA_SQ_M")) AS "ROTTERDAM_TOTAL_SURFACE_SQ_M"
    FROM NETHERLANDS_OPEN_MAP_DATA.NETHERLANDS."V_BUILDING"
    WHERE "CONTAINS_ADDRESSES" ILIKE '%Rotterdam%'
    GROUP BY "CLASS", "SUBCLASS"
)
SELECT
    COALESCE(a."CLASS",  r."CLASS")      AS "CLASS",
    COALESCE(a."SUBCLASS", r."SUBCLASS") AS "SUBCLASS",
    COALESCE(a."AMSTERDAM_BUILDING_COUNT",        0) AS "AMSTERDAM_BUILDING_COUNT",
    COALESCE(a."AMSTERDAM_TOTAL_SURFACE_SQ_M",    0) AS "AMSTERDAM_TOTAL_SURFACE_SQ_M",
    COALESCE(r."ROTTERDAM_BUILDING_COUNT",        0) AS "ROTTERDAM_BUILDING_COUNT",
    COALESCE(r."ROTTERDAM_TOTAL_SURFACE_SQ_M",    0) AS "ROTTERDAM_TOTAL_SURFACE_SQ_M"
FROM amsterdam a
FULL OUTER JOIN rotterdam r
  ON a."CLASS" = r."CLASS"
 AND a."SUBCLASS" = r."SUBCLASS"
ORDER BY
    "CLASS",
    "SUBCLASS";