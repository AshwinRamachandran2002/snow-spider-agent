WITH "largest_zip" AS (
    SELECT 
        "ZIP"
    FROM US_ADDRESSES__POI.CYBERSYN.US_ADDRESSES
    WHERE "STATE" = 'FL'
    GROUP BY "ZIP"
    ORDER BY COUNT(*) DESC
    LIMIT 1
)
SELECT
    "NUMBER",
    "STREET",
    "STREET_TYPE"
FROM US_ADDRESSES__POI.CYBERSYN.US_ADDRESSES AS ua
JOIN "largest_zip" lz
  ON ua."ZIP" = lz."ZIP"
WHERE ua."STATE" = 'FL'
ORDER BY ua."LATITUDE" DESC NULLS LAST
LIMIT 10;