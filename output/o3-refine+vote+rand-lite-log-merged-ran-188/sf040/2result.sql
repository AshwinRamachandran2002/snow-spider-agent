WITH fl_zip_counts AS (
    SELECT
        "ZIP",
        COUNT(*) AS "ADDRESS_COUNT"
    FROM US_ADDRESSES__POI.CYBERSYN.US_ADDRESSES
    WHERE "STATE" = 'FL'
    GROUP BY "ZIP"
),
largest_fl_zip AS (
    SELECT "ZIP"
    FROM fl_zip_counts
    QUALIFY ROW_NUMBER() OVER (ORDER BY "ADDRESS_COUNT" DESC, "ZIP") = 1
)

SELECT
    "NUMBER",
    "STREET",
    "STREET_TYPE"
FROM US_ADDRESSES__POI.CYBERSYN.US_ADDRESSES
WHERE "STATE" = 'FL'
  AND "ZIP" = (SELECT "ZIP" FROM largest_fl_zip)
ORDER BY "LATITUDE" DESC NULLS LAST
LIMIT 10;