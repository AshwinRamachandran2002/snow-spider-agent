SELECT
    "APP_GROUP_ID",
    TO_DATE(TO_TIMESTAMP("TIME")) AS "SESSION_START_DATE",
    COUNT(DISTINCT "USER_ID") AS "UNIQUE_USERS_SESSION_STARTED"
FROM BRAZE_USER_EVENT_DEMO_DATASET.PUBLIC."USERS_BEHAVIORS_APP_SESSIONSTART_VIEW"
WHERE TO_DATE(TO_TIMESTAMP("TIME")) BETWEEN '2023-06-01' AND '2023-06-07'
GROUP BY
    "APP_GROUP_ID",
    TO_DATE(TO_TIMESTAMP("TIME"))
ORDER BY
    "APP_GROUP_ID",
    "SESSION_START_DATE";