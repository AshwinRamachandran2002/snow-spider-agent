WITH asset_insured AS (
    SELECT
        a."ID_RSSD",
        a."VALUE" AS "TOTAL_ASSETS_USD",
        b."VALUE" AS "PCT_INSURED_EST"
    FROM FINANCE__ECONOMICS.CYBERSYN.FINANCIAL_INSTITUTION_TIMESERIES a
    JOIN FINANCE__ECONOMICS.CYBERSYN.FINANCIAL_INSTITUTION_TIMESERIES b
          ON a."ID_RSSD" = b."ID_RSSD"
    WHERE a."VARIABLE" = 'ASSET'
      AND b."VARIABLE" = 'ESTINS'
      AND a."DATE" = '2022-12-31'
      AND b."DATE" = '2022-12-31'
)

SELECT
    e."NAME"                                          AS "BANK_NAME",
    ROUND((1 - ai."PCT_INSURED_EST") * 100, 2)        AS "PCT_UNINSURED_ASSETS"
FROM asset_insured ai
JOIN FINANCE__ECONOMICS.CYBERSYN.FINANCIAL_INSTITUTION_ENTITIES e
      ON ai."ID_RSSD" = e."ID_RSSD"
WHERE e."IS_ACTIVE" = TRUE
  AND ai."TOTAL_ASSETS_USD" > 10000000000        -- > $10 billion
  AND ai."PCT_INSURED_EST" IS NOT NULL
ORDER BY "PCT_UNINSURED_ASSETS" DESC NULLS LAST
LIMIT 10;