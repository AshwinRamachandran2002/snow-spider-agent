/*  Weekly retention (weeks 1‑3) for users whose very first `first_open`
    occurred between 1 – 7 Sep 2018 (Asia/Shanghai)                       */

WITH events AS (
  -- Scan only September‑2018 tables
  SELECT
    user_pseudo_id,
    event_name,
    event_timestamp
  FROM `firebase-public-project.analytics_153293282.events_*`
  WHERE _TABLE_SUFFIX BETWEEN '20180901' AND '20180930'
),

-- 1) Cohort = users whose first `first_open` was 1‑7 Sep 2018
cohort_users AS (
  SELECT
    user_pseudo_id,
    DATE(TIMESTAMP_MICROS(MIN(event_timestamp)), 'Asia/Shanghai') AS first_open_date
  FROM events
  WHERE event_name = 'first_open'
  GROUP BY user_pseudo_id
  HAVING first_open_date BETWEEN '2018-09-01' AND '2018-09-07'
),

-- Cohort size
cohort_size AS (
  SELECT COUNT(DISTINCT user_pseudo_id) AS n
  FROM cohort_users
),

-- 2) All September events generated by the cohort
user_returns AS (
  SELECT
    e.user_pseudo_id,
    DATE(TIMESTAMP_MICROS(e.event_timestamp), 'Asia/Shanghai') AS event_date
  FROM events e
  JOIN cohort_users c
  ON e.user_pseudo_id = c.user_pseudo_id
)

-- 3) Retention calculation for weeks 1‑3
SELECT
  ROUND(
    COUNT(DISTINCT IF(event_date BETWEEN '2018-09-08' AND '2018-09-14',
                      user_pseudo_id, NULL)) / ANY_VALUE(n), 4) AS week_1_retention,
  ROUND(
    COUNT(DISTINCT IF(event_date BETWEEN '2018-09-15' AND '2018-09-21',
                      user_pseudo_id, NULL)) / ANY_VALUE(n), 4) AS week_2_retention,
  ROUND(
    COUNT(DISTINCT IF(event_date BETWEEN '2018-09-22' AND '2018-09-28',
                      user_pseudo_id, NULL)) / ANY_VALUE(n), 4) AS week_3_retention
FROM user_returns
CROSS JOIN cohort_size;