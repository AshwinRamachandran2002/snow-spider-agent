WITH "PYTHON_REPOS" AS (
    SELECT "repo_name"
    FROM GITHUB_REPOS.GITHUB_REPOS.LANGUAGES
    WHERE "language":"Python" IS NOT NULL
),
"COMMITS_2016" AS (
    SELECT 
        TO_TIMESTAMP( ("author":"date")::NUMBER / 1000000 ) AS "AUTHOR_TS",
        "repo_name"
    FROM GITHUB_REPOS.GITHUB_REPOS.SAMPLE_COMMITS
    WHERE "repo_name" IN (SELECT "repo_name" FROM "PYTHON_REPOS")
      AND TO_TIMESTAMP( ("author":"date")::NUMBER / 1000000 ) 
          BETWEEN '2016-01-01' AND '2016-12-31 23:59:59'
),
"MONTHLY_COUNTS" AS (
    SELECT 
        DATE_TRUNC('month', "AUTHOR_TS") AS "MONTH",
        COUNT(*) AS "COMMITS"
    FROM "COMMITS_2016"
    GROUP BY "MONTH"
)
SELECT AVG("COMMITS") AS "AVG_COMMITS_PER_MONTH_2016"
FROM "MONTHLY_COUNTS";