WITH prices AS (
    SELECT
        "TICKER",
        "DATE",
        "VALUE"
    FROM FINANCE__ECONOMICS.CYBERSYN.STOCK_PRICE_TIMESERIES
    WHERE "VARIABLE" = 'post-market_close'
      AND "TICKER" IN ('AAPL','MSFT','AMZN','GOOGL','META','NVDA','TSLA')
      AND "DATE" BETWEEN '2024-01-01' AND '2024-06-30'
), start_prices AS (
    SELECT
        "TICKER",
        "VALUE" AS "START_PRICE"
    FROM prices
    QUALIFY "DATE" = MIN("DATE") OVER (PARTITION BY "TICKER")
), end_prices AS (
    SELECT
        "TICKER",
        "VALUE" AS "END_PRICE"
    FROM prices
    QUALIFY "DATE" = MAX("DATE") OVER (PARTITION BY "TICKER")
)
SELECT
    s."TICKER",
    ROUND(((e."END_PRICE" - s."START_PRICE") / s."START_PRICE") * 100, 4) AS "PCT_CHANGE_JAN1_TO_JUN30_2024"
FROM start_prices s
JOIN end_prices   e ON s."TICKER" = e."TICKER"
ORDER BY "PCT_CHANGE_JAN1_TO_JUN30_2024" DESC NULLS LAST;