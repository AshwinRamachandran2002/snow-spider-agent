WITH "FL_ADDRESSES" AS (
    SELECT 
        "ADDRESS_ID",
        "ZIP",
        "LATITUDE",
        "NUMBER",
        "STREET",
        "STREET_TYPE"
    FROM "US_ADDRESSES__POI"."CYBERSYN"."US_ADDRESSES"
    WHERE "STATE" = 'FL'
      AND "LATITUDE" IS NOT NULL
      AND "ZIP" IS NOT NULL
), 
"LARGEST_ZIP" AS (
    SELECT "ZIP"
    FROM "FL_ADDRESSES"
    GROUP BY "ZIP"
    ORDER BY COUNT(*) DESC, "ZIP"
    LIMIT 1
), 
"ZIP_ADDRESSES" AS (
    SELECT *
    FROM "FL_ADDRESSES"
    WHERE "ZIP" = (SELECT "ZIP" FROM "LARGEST_ZIP")
)
SELECT
    "NUMBER"         AS "ADDRESS_NUMBER",
    "STREET"         AS "STREET_NAME",
    "STREET_TYPE"
FROM "ZIP_ADDRESSES"
ORDER BY "LATITUDE" DESC NULLS LAST, "ADDRESS_ID"
LIMIT 10;