WITH monthly_counts AS (
    SELECT
        EXTRACT(year  FROM CAST("block_timestamp" / 1000000 AS TIMESTAMP_NTZ))  AS "YEAR",
        EXTRACT(month FROM CAST("block_timestamp" / 1000000 AS TIMESTAMP_NTZ))  AS "MONTH",
        COUNT(*)                                                                          AS "MONTHLY_TRANSACTION_COUNT"
    FROM GOOG_BLOCKCHAIN.GOOG_BLOCKCHAIN_ARBITRUM_ONE_US."LOGS"
    WHERE EXTRACT(year FROM CAST("block_timestamp" / 1000000 AS TIMESTAMP_NTZ)) = 2023
    GROUP BY "YEAR", "MONTH"
)
SELECT
    "MONTHLY_TRANSACTION_COUNT",
    ROUND(
        "MONTHLY_TRANSACTION_COUNT" /
        (DAYOFMONTH(LAST_DAY(DATE_FROM_PARTS("YEAR","MONTH",1))) * 24 * 60 * 60),
        4
    ) AS "TRANSACTIONS_PER_SECOND",
    "YEAR",
    "MONTH"
FROM monthly_counts
ORDER BY "MONTHLY_TRANSACTION_COUNT" DESC NULLS LAST, "MONTH" DESC;