WITH "FILTERED_USERS" AS (
    SELECT 
        "age"
    FROM THELOOK_ECOMMERCE.THELOOK_ECOMMERCE."USERS"
    WHERE TO_DATE(TO_TIMESTAMP_NTZ("created_at" / 1000000)) BETWEEN '2019-01-01' AND '2022-04-30'
),
"AGE_BOUNDS" AS (
    SELECT 
        MAX("age") AS "MAX_AGE",
        MIN("age") AS "MIN_AGE"
    FROM "FILTERED_USERS"
),
"AGE_COUNTS" AS (
    SELECT
        SUM(CASE WHEN fu."age" = ab."MAX_AGE" THEN 1 ELSE 0 END) AS "OLDEST_USERS_COUNT",
        SUM(CASE WHEN fu."age" = ab."MIN_AGE" THEN 1 ELSE 0 END) AS "YOUNGEST_USERS_COUNT"
    FROM "FILTERED_USERS" fu
    CROSS JOIN "AGE_BOUNDS" ab
)
SELECT
    "OLDEST_USERS_COUNT",
    "YOUNGEST_USERS_COUNT",
    ABS("OLDEST_USERS_COUNT" - "YOUNGEST_USERS_COUNT") AS "DIFFERENCE_IN_NUMBER"
FROM "AGE_COUNTS";