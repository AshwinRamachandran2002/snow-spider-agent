-- Task: Compute the percentage change in 'Post-Market Close' prices for each of the Magnificent 7 tech companies (tickers: AAPL, MSFT, AMZN, GOOGL, META, TSLA, NVDA) between their earliest and latest available trading dates from January 1 to June 30, 2024.

WITH ytd_performance AS (
  SELECT
    TICKER,
    MIN(DATE) OVER (PARTITION BY TICKER) AS START_OF_YEAR_DATE,
    FIRST_VALUE(VALUE) OVER (
      PARTITION BY TICKER
      ORDER BY DATE ASC
      ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
    ) AS START_OF_YEAR_PRICE,
    MAX(DATE) OVER (PARTITION BY TICKER) AS LATEST_DATE,
    LAST_VALUE(VALUE) OVER (
      PARTITION BY TICKER
      ORDER BY DATE ASC
      ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
    ) AS LATEST_PRICE
  FROM FINANCE__ECONOMICS.CYBERSYN.STOCK_PRICE_TIMESERIES
  WHERE
    TICKER IN ('AAPL', 'MSFT', 'AMZN', 'GOOGL', 'META', 'TSLA', 'NVDA')
    AND DATE BETWEEN DATE '2024-01-01' AND DATE '2024-06-30'
    AND VARIABLE_NAME = 'Post-Market Close'
)
SELECT
  TICKER,
  (LATEST_PRICE - START_OF_YEAR_PRICE) / START_OF_YEAR_PRICE * 100 AS PERCENTAGE_CHANGE_YTD
FROM
  ytd_performance
GROUP BY
  TICKER, START_OF_YEAR_DATE, START_OF_YEAR_PRICE, LATEST_DATE, LATEST_PRICE
ORDER BY PERCENTAGE_CHANGE_YTD DESC;